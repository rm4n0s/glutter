// KeyboardKey is a keyboard key: a LogicalKeyboardKey or a PhysicalKeyboardKey.
//
// Flutter: services/keyboard_key.g.dart KeyboardKey
type KeyboardKey interface {
	foundation.Diagnosticable
	// DebugName is a name to print for the key; it is empty in release builds.
	DebugName() string
}

// KeySet is a set of keys: the logical keys that are pressed, the lock modes
// that are on. The zero value is an empty set that can be read but not added to;
// make one with NewKeySet.
//
// Flutter: no counterpart (dart:core Set)
type KeySet[K comparable] map[K]struct{}

// NewKeySet makes a set of the keys.
//
// Flutter: no counterpart (dart:core Set.of)
func NewKeySet[K comparable](keys ...K) KeySet[K] {
	s := make(KeySet[K], len(keys))
	for _, k := range keys {
		s[k] = struct{}{}
	}
	return s
}

// Contains is whether the key is in the set.
//
// Flutter: no counterpart (dart:core Set.contains)
func (s KeySet[K]) Contains(key K) bool {
	_, ok := s[key]
	return ok
}

// Equal is whether both sets have the same keys.
//
// Flutter: no counterpart (dart:core setEquals)
func (s KeySet[K]) Equal(other KeySet[K]) bool {
	if len(s) != len(other) {
		return false
	}
	for k := range s {
		if _, ok := other[k]; !ok {
			return false
		}
	}
	return true
}

// Clone copies the set.
//
// Flutter: no counterpart (dart:core Set.toSet)
func (s KeySet[K]) Clone() KeySet[K] {
	out := make(KeySet[K], len(s))
	for k := range s {
		out[k] = struct{}{}
	}
	return out
}

