// IsControlCharacter is whether the label is one Unicode control character, such
// as U+000A LINE FEED or U+001B ESCAPE.
//
// Flutter: services/keyboard_key.g.dart LogicalKeyboardKey.isControlCharacter
func IsControlCharacter(label string) bool {
	r, size := utf8.DecodeRuneInString(label)
	if size == 0 || size != len(label) || r == utf8.RuneError {
		return false
	}
	return r <= 0x1f || (r >= 0x7f && r <= 0x9f)
}

// IsAutogenerated is whether the id was made by Flutter for a platform key code
// that it does not recognize: its ids are not stable and should not be persisted.
//
// Flutter: services/keyboard_key.g.dart LogicalKeyboardKey.isAutogenerated
func (k LogicalKeyboardKey) IsAutogenerated() bool {
	return uint64(k)&LogicalKeyboardKeyPlaneMask >= LogicalKeyboardKeyStartOfPlatformPlanes
}

// Synonyms is the set of pseudo-keys that also stand for the key: the Shift key
// for ShiftLeft. It is empty for a key without synonyms.
//
// Flutter: services/keyboard_key.g.dart LogicalKeyboardKey.synonyms
func (k LogicalKeyboardKey) Synonyms() KeySet[LogicalKeyboardKey] {
	if s, ok := logicalKeySynonyms[k]; ok {
		return NewKeySet(s)
	}
	return KeySet[LogicalKeyboardKey]{}
}

// CollapseSynonyms replaces the keys that have a synonym by it: {ShiftLeft,
// ControlRight} becomes {Shift, Control}, to ask whether any control key is down.
//
// Flutter: services/keyboard_key.g.dart LogicalKeyboardKey.collapseSynonyms
func CollapseSynonyms(input KeySet[LogicalKeyboardKey]) KeySet[LogicalKeyboardKey] {
	out := KeySet[LogicalKeyboardKey]{}
	for k := range input {
		if s, ok := logicalKeySynonyms[k]; ok {
			out[s] = struct{}{}
		} else {
			out[k] = struct{}{}
		}
	}
	return out
}

// ExpandSynonyms replaces the pseudo-keys by the keys they stand for: {Control,
// Shift} becomes {ControlLeft, ControlRight, ShiftLeft, ShiftRight}.
//
// Flutter: services/keyboard_key.g.dart LogicalKeyboardKey.expandSynonyms
func ExpandSynonyms(input KeySet[LogicalKeyboardKey]) KeySet[LogicalKeyboardKey] {
	out := KeySet[LogicalKeyboardKey]{}
	for k := range input {
		if keys, ok := logicalKeyReverseSynonyms[k]; ok {
			for _, member := range keys {
				out[member] = struct{}{}
			}
		} else {
			out[k] = struct{}{}
		}
	}
	return out
}

// PhysicalKeyboardKey is a key at a place on the keyboard, whatever the modifiers,
