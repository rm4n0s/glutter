// LogicalKeyboardKey is a key interpreted in the context of the modifiers, the
// modes and the layout in effect: the key that has the label "Q" on it, wherever
// it is on the keyboard. The value is the key id. The named keys are generated
// constants such as LogicalKeyboardKeyKeyA and LogicalKeyboardKeyEnter, and two
// keys are equal when their ids are.
//
// Flutter: services/keyboard_key.g.dart LogicalKeyboardKey
type LogicalKeyboardKey uint64

// NewLogicalKeyboardKey makes the key of an id.
//
// Flutter: services/keyboard_key.g.dart LogicalKeyboardKey.new
func NewLogicalKeyboardKey(keyID uint64) LogicalKeyboardKey { return LogicalKeyboardKey(keyID) }

// KeyID is the unique code that represents the key. It is opaque: do not unpack
// it to derive information from it.
//
// Flutter: services/keyboard_key.g.dart LogicalKeyboardKey.keyId
func (k LogicalKeyboardKey) KeyID() uint64 { return uint64(k) }

func nonValueBits(n uint64) uint64 { return (n >> 32) & ((1 << 20) - 1) }

func unicodeKeyLabel(keyID uint64) (string, bool) {
	if nonValueBits(keyID) != 0 {
		return "", false
	}
	return strings.ToUpper(string(rune(keyID))), true
}

// KeyLabel is a description of the character that the key produces, for readable
// text: the printable character in upper case ("A", "1", "/", "Ù"), or the full
// name of the key ("F1", "Shift Left", "Media Down"), or an empty string when
// there is no label for the key. Do not use it to compare keys: compare the ids.
//
// Flutter: services/keyboard_key.g.dart LogicalKeyboardKey.keyLabel
func (k LogicalKeyboardKey) KeyLabel() string {
	if label, ok := unicodeKeyLabel(uint64(k)); ok {
		return label
	}
	return logicalKeyLabels[k]
}

// DebugName is the name to print for the key in debug builds, and empty in
// release builds: "Key A", "Digit 1", "Backslash", the name of a named key, or
// "Key with ID 0x00100012345".
//
// Flutter: services/keyboard_key.g.dart LogicalKeyboardKey.debugName
func (k LogicalKeyboardKey) DebugName() string {
	if !foundation.DebugMode {
		return ""
	}
	if name, ok := logicalKeyLabels[k]; ok {
		return name
	}
	if label, ok := unicodeKeyLabel(uint64(k)); ok {
		return "Key " + label
	}
	return fmt.Sprintf("Key with ID 0x%011x", uint64(k))
}

// String describes the key for logs and test failures.
//
// Flutter: services/keyboard_key.g.dart LogicalKeyboardKey.toString
func (k LogicalKeyboardKey) String() string {
	if name := k.DebugName(); name != "" {
		return "LogicalKeyboardKey(" + name + ")"
	}
	return fmt.Sprintf("LogicalKeyboardKey(0x%08x)", uint64(k))
}

// DebugFillProperties adds the id, the label and the debug name.
//
// Flutter: services/keyboard_key.g.dart LogicalKeyboardKey.debugFillProperties
func (k LogicalKeyboardKey) DebugFillProperties(p *foundation.DiagnosticPropertiesBuilder) {
	p.Add(foundation.NewStringProperty("keyId", foundation.Some(fmt.Sprintf("0x%08x", uint64(k)))))
	p.Add(foundation.NewStringProperty("keyLabel", foundation.Some(k.KeyLabel())))
	if name := k.DebugName(); name != "" {
		p.Add(foundation.NewStringProperty("debugName", foundation.Some(name)))
	}
}

