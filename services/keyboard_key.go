// PhysicalKeyOf returns the physical key that has the same name as the logical
// key, which is the key at that place on a QWERTY keyboard: KeyA for the logical
// "a", Enter for Enter, ArrowLeft for the left arrow. It returns false for the
// logical keys that have no place of their own (the pseudo-keys Shift and
// Control, the symbols that need Shift). Tests use it to simulate a key press
// from a logical key.
//
// Flutter: flutter_test/lib/src/event_simulation.dart KeyEventSimulator._getPhysicalKey
func PhysicalKeyOf(logical LogicalKeyboardKey) (PhysicalKeyboardKey, bool) {
	k, ok := logicalToPhysicalKey[logical]
	return k, ok
}
