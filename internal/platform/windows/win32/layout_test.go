// u32 is a constant of the headers as the unsigned 32-bit number they write: a negative one, such as
// GWLP_USERDATA, is its two's complement.
func u32[T ~int | ~uint32 | ~int32 | ~uint16](v T) uint32 { return uint32(int32(v)) }
