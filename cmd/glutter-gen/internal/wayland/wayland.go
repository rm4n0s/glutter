// Package wayland implements the `glutter-gen wayland` subcommand: it reads the
// Wayland protocol XML files and writes the Go bindings, one *_gen.go file per
// protocol, for package wl.
//
// Flutter: no counterpart.
package wayland

import (
	"bytes"
	"flag"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/rm4n0s/errors"
)

const (
	defaultProtocolsDir = "internal/platform/linux/wayland/protocols"
	defaultOutDir       = "internal/platform/linux/wayland/wl"
)

// Run executes `glutter-gen wayland [-protocols dir] [-out dir]` with the
// arguments that follow the subcommand name. It generates from every *.xml file
// in the protocols directory and replaces the *_gen.go files in the output
// directory; generated files of protocols that are gone are removed.
//
// Flutter: no counterpart
func Run(args []string) error {
	flags := flag.NewFlagSet("wayland", flag.ContinueOnError)
	flags.SetOutput(io.Discard)
	protocolsDir := flags.String("protocols", defaultProtocolsDir, "directory with the protocol XML files")
	outDir := flags.String("out", defaultOutDir, "directory to write the *_gen.go files to")
	if err := flags.Parse(args); err != nil {
		return errors.NewErr("WaylandBadFlags", err).SetMetadata("args", args)
	}
	files, err := generateDir(*protocolsDir)
	if err != nil {
		return err
	}
	return writeFiles(*outDir, files)
}

// generateDir generates the Go code for every XML file in dir.
func generateDir(dir string) ([]generatedFile, error) {
	protocols, err := loadProtocols(dir)
	if err != nil {
		return nil, err
	}
	reg, err := newRegistry(protocols)
	if err != nil {
		return nil, err
	}
	return generate(reg)
}

// loadProtocols reads and parses every *.xml file in dir, in name order.
func loadProtocols(dir string) ([]*protocol, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, errors.NewErr("WaylandXMLReadFailed", err).SetMetadata("dir", dir)
	}
	var protocols []*protocol
	for _, e := range entries {
		if e.IsDir() || filepath.Ext(e.Name()) != ".xml" {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil {
			return nil, errors.NewErr("WaylandXMLReadFailed", err).SetMetadata("file", e.Name())
		}
		p, err := parseProtocol(data, e.Name())
		if err != nil {
			return nil, err
		}
		protocols = append(protocols, p)
	}
	if len(protocols) == 0 {
		return nil, errors.New("WaylandXMLReadFailed", "no .xml files found", "dir", dir)
	}
	return protocols, nil
}

// writeFiles writes the generated files into dir, leaving unchanged files
// alone, and removes generated files that are no longer produced.
func writeFiles(dir string, files []generatedFile) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return errors.NewErr("WaylandWriteFailed", err).SetMetadata("dir", dir)
	}
	want := map[string]bool{}
	for _, f := range files {
		want[f.name] = true
		path := filepath.Join(dir, f.name)
		if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, f.data) {
			continue
		}
		if err := os.WriteFile(path, f.data, 0o644); err != nil {
			return errors.NewErr("WaylandWriteFailed", err).SetMetadata("file", path)
		}
	}
	existing, err := filepath.Glob(filepath.Join(dir, "*_gen.go"))
	if err != nil {
		return errors.NewErr("WaylandWriteFailed", err).SetMetadata("dir", dir)
	}
	for _, path := range existing {
		if want[filepath.Base(path)] {
			continue
		}
		data, err := os.ReadFile(path)
		if err != nil || !strings.HasPrefix(string(data), "// Code generated by glutter-gen wayland") {
			continue // not ours
		}
		if err := os.Remove(path); err != nil {
			return errors.NewErr("WaylandWriteFailed", err).SetMetadata("file", path)
		}
	}
	return nil
}
