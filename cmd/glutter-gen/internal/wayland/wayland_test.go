// TestGeneratedBindingsAreUpToDate fails when the protocols or the generator
// changed and `go generate ./internal/platform/linux/wayland/...` was not run.
func TestGeneratedBindingsAreUpToDate(t *testing.T) {
	root := filepath.Join("..", "..", "..", "..")
	protocols := filepath.Join(root, defaultProtocolsDir)
	out := filepath.Join(root, defaultOutDir)

	files, err := generateDir(protocols)
	if err != nil {
		t.Fatal(err)
	}
	if len(files) < 18 {
		t.Errorf("generated %d files, want one for each of the 18 protocols", len(files))
	}
	want := map[string]bool{}
	for _, f := range files {
		want[f.name] = true
		got, err := os.ReadFile(filepath.Join(out, f.name))
		if err != nil {
			t.Errorf("%s is missing: %v; run go generate ./internal/platform/linux/wayland/...", f.name, err)
			continue
		}
		if string(got) != string(f.data) {
			t.Errorf("%s is out of date; run go generate ./internal/platform/linux/wayland/...", f.name)
		}
		if !strings.HasPrefix(string(got), "// Code generated by glutter-gen wayland from ") || !strings.Contains(strings.SplitN(string(got), "\n", 2)[0], "DO NOT EDIT.") {
			t.Errorf("%s does not start with the \"Code generated ... DO NOT EDIT.\" header", f.name)
		}
	}
	existing, err := filepath.Glob(filepath.Join(out, "*_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	for _, path := range existing {
		if !want[filepath.Base(path)] {
			t.Errorf("%s is left over from a protocol that no longer exists", path)
		}
	}
}

func TestGoType(t *testing.T) {
	r, err := newRegistry(mustParse(t, "small", mustRead(t, filepath.Join("testdata", "small", "small.xml"))))
	if err != nil {
		t.Fatal(err)
	}
	g := &generator{r: r}
	thing := r.ifaces["demo_thing"]
	// The XML does not say what an array holds: listed arrays are []uint32.
	keyboard := &iface{Name: "wl_keyboard"}
	toplevel := &iface{Name: "xdg_toplevel"}
	textInput := &iface{Name: "zwp_text_input_v3"}

	tests := []struct {
		name string
		from *iface
		msg  string
		arg  *arg
		want string
	}{
		{"int", thing, "poke", &arg{Type: typeInt}, "int32"},
		{"int with an enum of the same interface", thing, "configure", &arg{Type: typeInt, Enum: "mode"}, "DemoThingMode"},
		{"uint with an enum of another interface", thing, "poke", &arg{Type: typeUint, Enum: "demo_registry.kind"}, "DemoRegistryKind"},
		{"uint", thing, "poke", &arg{Type: typeUint}, "uint32"},
		{"fixed", thing, "motion", &arg{Type: typeFixed}, "float64"},
		{"string", thing, "motion", &arg{Type: typeString}, "string"},
		{"typed object", thing, "entered", &arg{Type: typeObject, Interface: "demo_thing"}, "*DemoThing"},
		{"untyped object", thing, "entered", &arg{Type: typeObject}, "Object"},
		{"typed new_id", thing, "child", &arg{Type: typeNewID, Interface: "demo_thing"}, "*DemoThing"},
		{"fd", thing, "motion", &arg{Type: typeFD}, "int"},
		{"array that is not listed", thing, "configure", &arg{Type: typeArray, Name: "data"}, "[]byte"},
		{"wl_keyboard.enter keys", keyboard, "enter", &arg{Type: typeArray, Name: "keys"}, "[]uint32"},
		{"xdg_toplevel.configure states", toplevel, "configure", &arg{Type: typeArray, Name: "states"}, "[]uint32"},
		{"xdg_toplevel.wm_capabilities", toplevel, "wm_capabilities", &arg{Type: typeArray, Name: "capabilities"}, "[]uint32"},
		{"request array of uint32", textInput, "set_available_actions", &arg{Type: typeArray, Name: "available_actions"}, "[]uint32"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := g.goType(tt.from, tt.msg, tt.arg); got != tt.want {
				t.Errorf("goType = %q, want %q", got, tt.want)
			}
		})
	}
}

