// protocolXML wraps interface XML in a protocol element.
func protocolXML(body string) string {
	return `<protocol name="t"><copyright>c</copyright>` + body + `</protocol>`
}

func TestRunFailures(t *testing.T) {
	validIface := `<interface name="a" version="1"><description summary="a"/></interface>`
	tests := []struct {
		name    string
		files   map[string]string // XML files to write; nil leaves the directory missing
		args    []string
		wantTag string
		route   string
	}{
		{"bad flag", map[string]string{}, []string{"-nope"}, "WaylandBadFlags", "Run.WaylandBadFlags"},
		{"protocols directory missing", nil, nil, "WaylandXMLReadFailed", "Run->generateDir->loadProtocols.WaylandXMLReadFailed"},
		{"no XML files", map[string]string{"readme.txt": "x"}, nil, "WaylandXMLReadFailed", "loadProtocols.WaylandXMLReadFailed"},
		{"broken XML", map[string]string{"a.xml": "<protocol"}, nil, "WaylandXMLParseFailed", "loadProtocols->parseProtocol.WaylandXMLParseFailed"},
		{
			"interface defined in two files",
			map[string]string{"a.xml": protocolXML(validIface), "b.xml": protocolXML(validIface)},
			nil, "WaylandXMLInvalid", "generateDir->newRegistry.WaylandXMLInvalid",
		},
		{
			"unknown argument type",
			map[string]string{"a.xml": protocolXML(`<interface name="a" version="1"><request name="r"><arg name="x" type="float"/></request></interface>`)},
			nil, "WaylandXMLInvalid", "newRegistry->registry.check.WaylandXMLInvalid",
		},
		{
			"object of an unknown interface",
			map[string]string{"a.xml": protocolXML(`<interface name="a" version="1"><event name="e"><arg name="x" type="object" interface="ghost"/></event></interface>`)},
			nil, "WaylandXMLInvalid", "newRegistry->registry.check.WaylandXMLInvalid",
		},
		{
			"enum that does not exist",
			map[string]string{"a.xml": protocolXML(`<interface name="a" version="1"><event name="e"><arg name="x" type="uint" enum="ghost"/></event></interface>`)},
			nil, "WaylandXMLInvalid", "newRegistry->registry.check.WaylandXMLInvalid",
		},
		{
			"enum on a string",
			map[string]string{"a.xml": protocolXML(`<interface name="a" version="1"><enum name="e"><entry name="x" value="0"/></enum><event name="ev"><arg name="x" type="string" enum="e"/></event></interface>`)},
			nil, "WaylandXMLInvalid", "newRegistry->registry.check.WaylandXMLInvalid",
		},
		{
			"two new_id arguments",
			map[string]string{"a.xml": protocolXML(`<interface name="a" version="1"><request name="r"><arg name="x" type="new_id" interface="a"/><arg name="y" type="new_id" interface="a"/></request></interface>`)},
			nil, "WaylandXMLInvalid", "newRegistry->registry.check.WaylandXMLInvalid",
		},
		{
			"unknown request type",
			map[string]string{"a.xml": protocolXML(`<interface name="a" version="1"><request name="r" type="constructor"/></interface>`)},
			nil, "WaylandXMLInvalid", "newRegistry->registry.check.WaylandXMLInvalid",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := filepath.Join(t.TempDir(), "protocols")
			if tt.files != nil {
				if err := os.MkdirAll(dir, 0o755); err != nil {
					t.Fatal(err)
				}
				for name, content := range tt.files {
					if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
						t.Fatal(err)
					}
				}
			}
			args := append([]string{"-protocols", dir, "-out", t.TempDir()}, tt.args...)
			err := Run(args)
			appErr, ok := errors.FromError(err)
			if !ok {
				t.Fatalf("expected *errors.Error, got %T (%v)", err, err)
			}
			if appErr.Tag != tt.wantTag {
				t.Errorf("Tag = %q, want %q (%s)", appErr.Tag, tt.wantTag, appErr.Message)
			}
			if !appErr.HasRoute(tt.route) {
				t.Errorf("unexpected failure path: %s, want it to contain %s", appErr.Route(), tt.route)
			}
		})
	}
}

func TestRunWriteFailure(t *testing.T) {
	// The output directory is a file, so creating it fails.
	out := filepath.Join(t.TempDir(), "file")
	if err := os.WriteFile(out, nil, 0o644); err != nil {
		t.Fatal(err)
	}
	err := Run([]string{"-protocols", filepath.Join("testdata", "small"), "-out", filepath.Join(out, "sub")})
	appErr, ok := errors.FromError(err)
	if !ok {
		t.Fatalf("expected *errors.Error, got %T (%v)", err, err)
	}
	if appErr.Tag != tagWaylandWriteFailed || !appErr.HasRoute("Run->writeFiles.WaylandWriteFailed") {
		t.Errorf("Tag = %q, route = %s, want WaylandWriteFailed via Run->writeFiles", appErr.Tag, appErr.Route())
	}
}

func TestRunWritesAndCleansUp(t *testing.T) {
	out := t.TempDir()
	stale := filepath.Join(out, "gone_gen.go")
	foreign := filepath.Join(out, "mine_gen.go")
	hand := filepath.Join(out, "runtime.go")
	for path, content := range map[string]string{
		stale:   "// Code generated by glutter-gen wayland from gone.xml. DO NOT EDIT.\n\npackage wl\n",
		foreign: "// Code generated by some other tool. DO NOT EDIT.\n\npackage wl\n",
		hand:    "package wl\n",
	} {
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	for range 2 { // the second run changes nothing
		if err := Run([]string{"-protocols", filepath.Join("testdata", "small"), "-out", out}); err != nil {
			t.Fatal(err)
		}
	}
	if _, err := os.Stat(filepath.Join(out, "small_gen.go")); err != nil {
		t.Errorf("small_gen.go was not written: %v", err)
	}
	if _, err := os.Stat(stale); !os.IsNotExist(err) {
		t.Errorf("the stale generated file was not removed (stat error: %v)", err)
	}
	for _, kept := range []string{foreign, hand} {
		if _, err := os.Stat(kept); err != nil {
			t.Errorf("%s must be left alone: %v", kept, err)
		}
	}
}

func mustRead(t *testing.T, path string) []byte {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return data
}

func mustParse(t *testing.T, file string, data []byte) []*protocol {
	t.Helper()
	p, err := parseProtocol(data, file)
	if err != nil {
		t.Fatal(err)
	}
	return []*protocol{p}
}
