var updateGoldens = flag.Bool("update-goldens", false, "rewrite the golden files")

func TestGenerateSmallGolden(t *testing.T) {
	files, err := generateDir(filepath.Join("testdata", "small"))
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != 1 || files[0].name != "small_gen.go" {
		t.Fatalf("generated %d files, want only small_gen.go", len(files))
	}
	golden := filepath.Join("testdata", "small_gen.go.golden")
	if *updateGoldens {
		if err := os.WriteFile(golden, files[0].data, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatal(err)
	}
	if string(files[0].data) != string(want) {
		t.Errorf("generated code differs from %s; run: go test ./cmd/glutter-gen/internal/wayland -run Golden -update-goldens, then review the diff", golden)
	}
	if !strings.HasPrefix(string(files[0].data), "// Code generated by glutter-gen wayland from small.xml. DO NOT EDIT.") {
		t.Errorf("the generated file does not start with the generated-code header:\n%.200s", files[0].data)
	}
}

