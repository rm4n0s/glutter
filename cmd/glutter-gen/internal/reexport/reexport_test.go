func options(t *testing.T, specs []Spec, declared map[string]bool) Options {
	t.Helper()
	imp := memImporter{}
	foundation := check(t, imp, "example.com/m/foundation", basicSrc)
	widgets := check(t, imp, "example.com/m/widgets", widgetsSrc)
	rendering := check(t, imp, "example.com/m/rendering", extraSrc)
	return Options{Module: "example.com/m", Target: "material", Specs: specs, Declared: declared,
		Packages: map[string]*types.Package{"foundation": foundation, "widgets": widgets, "rendering": rendering}}
}

func TestMatches(t *testing.T) {
	tests := []struct {
		ident string
		names []string
		want  bool
	}{
		{"Axis", []string{"Axis"}, true},
		{"AxisDirection", []string{"Axis"}, true},
		{"NewAxis", []string{"Axis"}, true},
		{"NewAxisDirection", []string{"Axis"}, true},
		{"Axes", []string{"Axis"}, false},
		{"Axisx", []string{"Axis"}, false},
		{"Renderer", []string{"Render"}, false},
		{"RenderBox", []string{"RenderBox"}, true},
		{"RenderBoxHelper", []string{"RenderBox"}, true},
		{"DebugPrint", []string{"debugPrint"}, true},
		{"Key", []string{"Key"}, true},
		{"KeyEvent", []string{"Key"}, true},
		{"Keyboard", []string{"Key"}, false},
		{"X", []string{""}, false},
		{"Size2D", []string{"Size"}, true},
	}
	for _, tt := range tests {
		t.Run(tt.ident, func(t *testing.T) {
			if got := matches(tt.ident, tt.names); got != tt.want {
				t.Errorf("matches(%q, %v) = %v, want %v", tt.ident, tt.names, got, tt.want)
			}
		})
	}
}

func TestGenerate(t *testing.T) {
	specs := []Spec{
		{Package: "widgets", All: true},
		{Package: "foundation", Names: []string{"Key", "ValueChanged"}, Extra: []string{"Opt", "Some"}},
		{Package: "rendering", Names: []string{"RenderBox", "Axis"}},
	}
	code, err := Generate(options(t, specs, map[string]bool{"Declared": true}))
	if err != nil {
		t.Fatal(err)
	}
	got := strings.Join(strings.Fields(string(code)), " ")
	for _, want := range []string{
		"// Code generated by glutter-gen reexport; DO NOT EDIT.",
		"package material",
		// aliases, generic ones included
		"type Widget = widgets.Widget",
		"type Opt[T any] = foundation.Opt[T]",
		"type ValueChanged[T any] = foundation.ValueChanged[T]",
		"type Key = foundation.Key",
		// functions: results, variadic, generic, hidden package names, blank parameters
		"func NewText(data string, opts ...widgets.TextOpts) *widgets.Text { return widgets.NewText(data, opts...) }",
		"func NewPadding(a0 foundation.Opt[int], child widgets.Widget) (*widgets.Text, error) { return widgets.NewPadding(a0, child) }",
		"func Pair[K comparable, V any](k K, v V, rest ...V) map[K]V { return widgets.Pair[K, V](k, v, rest...) }",
		"func NoResult(a int, a1 int) { widgets.NoResult(a, a1) }",
		"func Callback(a0 func(int) string) { widgets.Callback(a0) }",
		"func Some[T any](v T) foundation.Opt[T] { return foundation.Some[T](v) }",
		"func Takes[T interface{ ~int | ~string }](v T) T { return widgets.Takes[T](v) }",
		// constants and variables
		"const ModeA = widgets.ModeA",
		"const Untyped = widgets.Untyped",
		"var Colors = widgets.Colors",
		// the doc comments end with the Flutter source
		"// Widget is widgets.Widget. // // Flutter: widgets.dart Widget",
		"// Key is foundation.Key. // // Flutter: foundation.dart Key",
		// the names of a spec: the class and its functions, not the others
		"type RenderBox = rendering.RenderBox",
		"type RenderBoxHelper = rendering.RenderBoxHelper",
		"func NewRenderBox() *rendering.RenderBox { return rendering.NewRenderBox() }",
		"func AxisDirectionToAxis(d rendering.AxisDirection) rendering.Axis { return rendering.AxisDirectionToAxis(d) }",
	} {
		if !strings.Contains(got, strings.Join(strings.Fields(want), " ")) {
			t.Errorf("the code lacks %q", want)
		}
	}
	for _, unwanted := range []string{
		"TakesHidden",    // an unexported parameter type cannot be named
		"var Counter",    // a copy of a variable of a basic type would not follow the writes
		"var Declared",   // the target declares it
		"type Renderer",  // not one of the names
		"func Unrelated", // not one of the names
		"DebugMode",      // not one of the names
	} {
		if strings.Contains(got, unwanted+" ") && !strings.Contains(got, "// "+unwanted) {
			t.Errorf("the code has %q", unwanted)
		}
	}
	if !strings.Contains(got, "// Not re-exported, because the package declares an identifier of the same name: // widgets.Declared") {
		t.Errorf("the code does not say that Declared was skipped:\n%s", code)
	}
	if !strings.Contains(got, "widgets.Counter") {
		t.Error("the code should say that Counter is not copied")
	}
	// The imports are the packages that the wrappers name, sorted.
	if !strings.Contains(got, `import ( "example.com/m/foundation" "example.com/m/rendering" "example.com/m/widgets" )`) {
		t.Errorf("unexpected imports in\n%s", code)
	}
}

func TestGeneratePriority(t *testing.T) {
	// The first package that has a name wins.
	imp := memImporter{}
	a := check(t, imp, "example.com/m/a", "package a\n\ntype Same struct{}\n\nfunc OnlyA() {}\n")
	b := check(t, imp, "example.com/m/b", "package b\n\ntype Same struct{}\n\nfunc OnlyB() {}\n")
	code, err := Generate(Options{Module: "example.com/m", Target: "material", Specs: []Spec{{Package: "a", All: true}, {Package: "b", All: true}},
		Packages: map[string]*types.Package{"a": a, "b": b}})
	if err != nil {
		t.Fatal(err)
	}
	got := string(code)
	if !strings.Contains(got, "type Same = a.Same") || strings.Contains(got, "b.Same") {
		t.Errorf("the first package should win:\n%s", got)
	}
	if !strings.Contains(got, "OnlyA") || !strings.Contains(got, "OnlyB") {
		t.Errorf("both packages should be re-exported:\n%s", got)
	}
}

func TestGenerateSkipsInternalPackages(t *testing.T) {
	imp := memImporter{}
	check(t, imp, "example.com/m/internal/hidden", "package hidden\n\ntype T struct{}\n")
	pub := check(t, imp, "example.com/m/pub", `package pub

import "example.com/m/internal/hidden"

func Leaks(h hidden.T) {}

func Fine(x int) int { return x }
`)
	code, err := Generate(Options{Module: "example.com/m", Target: "material", Specs: []Spec{{Package: "pub", All: true}}, Packages: map[string]*types.Package{"pub": pub}})
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(code), "Leaks") || !strings.Contains(string(code), "Fine") {
		t.Errorf("a function that has an internal type in its signature should be skipped:\n%s", code)
	}
}

func TestGenerateErrors(t *testing.T) {
	tests := []struct {
		name      string
		change    func(o *Options)
		wantRoute string
	}{
		{"package missing", func(o *Options) { o.Specs = []Spec{{Package: "absent", All: true}} }, "Generate.ReexportPackageMissing"},
		{"target is not a package name", func(o *Options) { o.Target = "bad name" }, "Generate.ReexportFormatFailed"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			o := options(t, []Spec{{Package: "widgets", All: true}}, nil)
			tt.change(&o)
			_, err := Generate(o)
			appErr, ok := errors.FromError(err)
			if !ok {
				t.Fatalf("expected *errors.Error, got %T (%v)", err, err)
			}
			if !appErr.HasRoute(tt.wantRoute) {
				t.Errorf("unexpected failure path: %s, want it to contain %s", appErr.Route(), tt.wantRoute)
			}
		})
	}
}

func TestDefaultSpecs(t *testing.T) {
	specs := DefaultSpecs()
	all := map[string]bool{}
	for _, s := range specs {
		all[s.Package] = s.All
		if !s.All && len(s.Names) == 0 {
			t.Errorf("the spec of %s selects nothing", s.Package)
		}
	}
	for _, p := range []string{"widgets", "animation", "painting"} {
		if !all[p] {
			t.Errorf("%s should be re-exported whole", p)
		}
	}
	for _, p := range []string{"ui", "foundation", "rendering", "gestures", "services", "physics", "scheduler"} {
		if _, ok := all[p]; !ok || all[p] {
			t.Errorf("%s should be re-exported by name", p)
		}
	}
}

// tinyModule makes a module with the packages of the default specs, each with a
// type, and a target package with a declaration of its own.
func tinyModule(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	write := func(rel, content string) {
		t.Helper()
		path := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", "module example.com/m\n\ngo 1.22\n")
	for _, s := range DefaultSpecs() {
		name := s.Package
		write(name+"/"+name+".go", "package "+name+"\n\ntype Widget struct{}\n\nfunc NewWidget() *Widget { return nil }\n\nfunc Only"+strings.ToUpper(name[:1])+name[1:]+"() {}\n")
	}
	write("material/own.go", "package material\n\nfunc OnlyWidgets() {}\n")
	write("material/own_test.go", "package material\n\nfunc OnlyTest() {}\n")
	write("material/skipped_gen.go", "package material\n\nfunc OnlyGenerated() {}\n")
	return dir
}

func TestRun(t *testing.T) {
	dir := tinyModule(t)
	t.Chdir(dir)
	args := []string{"-module", "example.com/m", "-target", "material", "-out", "material/widgets_reexport_gen.go"}
	if err := Run(args); err != nil {
		t.Fatal(err)
	}
	out := filepath.Join(dir, "material", "widgets_reexport_gen.go")
	code, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	got := strings.Join(strings.Fields(string(code)), " ")
	for _, want := range []string{
		"package material",
		"type Widget = widgets.Widget",
		"func NewWidget() *widgets.Widget { return widgets.NewWidget() }",
		"func OnlyAnimation() { animation.OnlyAnimation() }",
		"func OnlyPainting() { painting.OnlyPainting() }",
		// OnlyWidgets is declared by the package, so it is not re-exported.
		"// widgets.OnlyWidgets",
	} {
		if !strings.Contains(got, strings.Join(strings.Fields(want), " ")) {
			t.Errorf("the code lacks %q", want)
		}
	}
	if strings.Contains(got, "func OnlyWidgets") {
		t.Error("OnlyWidgets is declared by the package and must not be re-exported")
	}
	// A second run changes nothing.
	info1, _ := os.Stat(out)
	if err := Run(args); err != nil {
		t.Fatal(err)
	}
	info2, _ := os.Stat(out)
	if !info1.ModTime().Equal(info2.ModTime()) {
		t.Error("a second run rewrote an identical file")
	}
}

func TestRunErrors(t *testing.T) {
	tests := []struct {
		name      string
		args      []string
		prepare   func(t *testing.T)
		wantRoute string
	}{
		{"bad flags", []string{"-nope"}, nil, "Run.ReexportBadFlags"},
		{"target directory missing", []string{"-target", "absent"}, nil, "Run->declaredNames.ReexportReadDirFailed"},
		{"a file of the target does not parse", []string{"-module", "example.com/m"}, func(t *testing.T) {
			if err := os.WriteFile(filepath.Join("material", "broken.go"), []byte("package material\n\nfunc {"), 0o644); err != nil {
				t.Fatal(err)
			}
		}, "Run->declaredNames.ReexportParseFailed"},
		{"the target has no Go file", []string{"-module", "example.com/m", "-target", "empty"}, func(t *testing.T) {
			if err := os.Mkdir("empty", 0o755); err != nil {
				t.Fatal(err)
			}
		}, "Run->declaredNames.ReexportTargetEmpty"},
		{"a package cannot be imported", []string{"-module", "example.com/other"}, nil, "Run.ReexportImportFailed"},
		{"the output cannot be written", []string{"-module", "example.com/m", "-out", "absent/dir/file.go"}, nil, "Run.ReexportWriteFailed"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Chdir(tinyModule(t))
			if tt.prepare != nil {
				tt.prepare(t)
			}
			err := Run(tt.args)
			appErr, ok := errors.FromError(err)
			if !ok {
				t.Fatalf("expected *errors.Error, got %T (%v)", err, err)
			}
			if !appErr.HasRoute(tt.wantRoute) {
				t.Errorf("unexpected failure path: %s, want it to contain %s", appErr.Route(), tt.wantRoute)
			}
		})
	}

	t.Run("the working directory is gone", func(t *testing.T) {
		target := filepath.Join(tinyModule(t), "material")
		gone := filepath.Join(t.TempDir(), "gone")
		if err := os.Mkdir(gone, 0o755); err != nil {
			t.Fatal(err)
		}
		t.Chdir(gone)
		if err := os.Remove(gone); err != nil {
			t.Skip("cannot remove the working directory here")
		}
		err := Run([]string{"-target", target})
		appErr, ok := errors.FromError(err)
		if !ok || !appErr.HasRoute("Run.ReexportGetwdFailed") {
			t.Errorf("unexpected error %v", err)
		}
	})
}

