// Package icons implements the `glutter-gen icons` subcommand, which generates the Material icon constants.
//
// Flutter: no counterpart.
package icons

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"

	"github.com/rm4n0s/errors"
)

const (
	defaultReference = "reference/flutter"
	defaultOut       = "material/icons_gen.go"
	iconsFile        = "packages/flutter/lib/src/material/icons.dart"
)

// Icon is one icon read from icons.dart.
//
// Flutter: no counterpart.
type Icon struct {
	// DartName is the snake case name of the constant in Dart.
	DartName string
	// GoName is the name of the field of Go's Icons.
	GoName string
	// CodePoint is the code point of the glyph.
	CodePoint int
	// MatchTextDirection is whether the icon mirrors in right to left text.
	MatchTextDirection bool
}

var iconRE = regexp.MustCompile(`static const IconData (\w+) = IconData\(\s*(0x[0-9a-fA-F]+),\s*fontFamily: 'MaterialIcons',?\s*(matchTextDirection: true,)?\s*\);`)

// Run executes `glutter-gen icons [-reference dir] [-out file]` with the
// arguments that follow the subcommand name. It reads the Material icon
// constants of icons.dart in the Flutter checkout of the reference directory and
// writes material/icons_gen.go, which holds the read-only Icons value.
//
// Flutter: material/icons.dart Icons
func Run(args []string) error {
	flags := flag.NewFlagSet("icons", flag.ContinueOnError)
	flags.SetOutput(io.Discard)
	reference := flags.String("reference", defaultReference, "directory with the Flutter sources (see scripts/fetch-reference.sh)")
	out := flags.String("out", defaultOut, "file to write the icons to")
	if err := flags.Parse(args); err != nil {
		return errors.NewErr("IconsBadFlags", err).SetMetadata("args", args)
	}
	path := filepath.Join(*reference, iconsFile)
	src, err := os.ReadFile(path)
	if err != nil {
		return errors.NewErr("IconsReadFailed", err).SetMetadata("file", path)
	}
	icons, err := Parse(string(src))
	if err != nil {
		return err
	}
	code, err := Generate(icons)
	if err != nil {
		return err
	}
	if old, err := os.ReadFile(*out); err == nil && bytes.Equal(old, code) {
		return nil
	}
	if err := os.WriteFile(*out, code, 0o644); err != nil {
		return errors.NewErr("IconsWriteFailed", err).SetMetadata("file", *out)
	}
	return nil
}

// Parse reads the icon constants of the text of icons.dart.
//
// Flutter: no counterpart.
func Parse(src string) ([]Icon, error) {
	const marker = "// BEGIN GENERATED ICONS"
	if i := strings.Index(src, marker); i >= 0 {
		src = src[i:]
	}
	var icons []Icon
	seen := map[string]string{}
	for _, m := range iconRE.FindAllStringSubmatch(src, -1) {
		cp, err := strconv.ParseInt(m[2], 0, 32)
		if err != nil {
			return nil, errors.NewErr("IconsBadCodePoint", err).SetMetadata("icon", m[1])
		}
		goName := goName(m[1])
		if other, dup := seen[goName]; dup {
			return nil, errors.New("IconsDuplicateName", "two icons have the same Go name", "name", goName, "icons", []string{other, m[1]})
		}
		seen[goName] = m[1]
		icons = append(icons, Icon{DartName: m[1], GoName: goName, CodePoint: int(cp), MatchTextDirection: m[3] != ""})
	}
	if want := strings.Count(src, "static const IconData "); len(icons) != want {
		return nil, errors.New("IconsUnparsed", "some icon constants do not match the expected form", "parsed", len(icons), "found", want)
	}
	if len(icons) == 0 {
		return nil, errors.New("IconsNone", "no icon constants found")
	}
	return icons, nil
}

// goName turns a snake case Dart name into the exported Go name.
func goName(dart string) string {
	var b strings.Builder
	for _, part := range strings.Split(dart, "_") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	name := b.String()
	if name != "" && name[0] >= '0' && name[0] <= '9' {
		name = "Icon" + name
	}
	return name
}

// Generate writes the Go source of the icons.
//
// Flutter: no counterpart.
func Generate(icons []Icon) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by glutter-gen icons; DO NOT EDIT.\n")
	b.WriteString("// Source: Flutter's material/icons.dart. Copyright 2014 The Flutter Authors.\n")
	b.WriteString("// All rights reserved. Flutter is BSD-3-Clause licensed; see\n")
	b.WriteString("// third_party/flutter/LICENSE.\n\n")
	b.WriteString("package material\n\nimport \"github.com/rm4n0s/glutter/widgets\"\n\n")
	b.WriteString("// MaterialIconsFamily is the font family of the Material icons.\n//\n// Flutter: material/icons.dart Icons\nconst MaterialIconsFamily = \"MaterialIcons\"\n\n")
	b.WriteString("// IconSet holds the Material icons, as methods. A struct with a field per icon makes\n// the Go compiler run out of memory under -race (the cost grows faster than\n// the number of fields), so each icon is a method of this empty type.\n//\n// Flutter: material/icons.dart Icons\ntype IconSet struct{}\n\n")
	b.WriteString("// Icons holds the Material icons. It is read-only.\n//\n// Flutter: material/icons.dart Icons\nvar Icons IconSet\n\n")
	for _, ic := range icons {
		mirror := ""
		if ic.MatchTextDirection {
			mirror = ", MatchTextDirection: true"
		}
		fmt.Fprintf(&b, "// %s is the Material icon %q.\n//\n// Flutter: material/icons.dart Icons.%s\nfunc (IconSet) %s() widgets.IconData {\n\treturn widgets.IconData{CodePoint: %#x, FontFamily: MaterialIconsFamily%s}\n}\n\n", ic.GoName, ic.DartName, ic.DartName, ic.GoName, ic.CodePoint, mirror)
	}
	code, err := format.Source(b.Bytes())
	if err != nil {
		return nil, errors.NewErr("IconsFormatFailed", err)
	}
	return code, nil
}
