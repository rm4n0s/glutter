const sample = `
abstract final class Icons {
  // BEGIN GENERATED ICONS

  /// doc
  static const IconData ten_k = IconData(0xe000, fontFamily: 'MaterialIcons');

  /// doc
  static const IconData arrow_back = IconData(
    0xe092,
    fontFamily: 'MaterialIcons',
    matchTextDirection: true,
  );

  static const IconData plain = IconData(
    0xe001,
    fontFamily: 'MaterialIcons',
  );
}
`

func TestParse(t *testing.T) {
	tests := []struct {
		name string
		src  string
		want []Icon
	}{
		{"mixed", sample, []Icon{
			{"ten_k", "TenK", 0xe000, false},
			{"arrow_back", "ArrowBack", 0xe092, true},
			{"plain", "Plain", 0xe001, false},
		}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := Parse(tt.src)
			if err != nil {
				t.Fatal(err)
			}
			if len(got) != len(tt.want) {
				t.Fatalf("got %d icons, want %d", len(got), len(tt.want))
			}
			for i := range got {
				if got[i] != tt.want[i] {
					t.Errorf("icon %d = %+v, want %+v", i, got[i], tt.want[i])
				}
			}
		})
	}
}

