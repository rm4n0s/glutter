func TestParseErrors(t *testing.T) {
	tests := []struct {
		name  string
		src   string
		route string
	}{
		{"duplicate", `static const IconData a_b = IconData(0xe000, fontFamily: 'MaterialIcons');
static const IconData a__b = IconData(0xe001, fontFamily: 'MaterialIcons');`, "Parse.IconsDuplicateName"},
		{"unparsed", `static const IconData a = IconData(0xe000, fontFamily: 'Other');`, "Parse.IconsUnparsed"},
		{"none", `nothing here`, "Parse.IconsNone"},
		{"bad code point", `static const IconData a = IconData(0xfffffffffff, fontFamily: 'MaterialIcons');`, "Parse.IconsBadCodePoint"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, err := Parse(tt.src)
			appErr, ok := errors.FromError(err)
			if !ok {
				t.Fatalf("expected *errors.Error, got %T (%v)", err, err)
			}
			if !appErr.HasRoute(tt.route) {
				t.Errorf("unexpected failure path: %s", appErr.Route())
			}
		})
	}
}

func TestGenerate(t *testing.T) {
	icons, err := Parse(sample)
	if err != nil {
		t.Fatal(err)
	}
	code, err := Generate(icons)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"// Code generated by glutter-gen icons; DO NOT EDIT.",
		"func (IconSet) TenK() widgets.IconData { return widgets.IconData{CodePoint: 0xe000, FontFamily: MaterialIconsFamily} }",
		"func (IconSet) ArrowBack() widgets.IconData { return widgets.IconData{CodePoint: 0xe092, FontFamily: MaterialIconsFamily, MatchTextDirection: true} }",
		"// Flutter: material/icons.dart Icons.arrow_back",
	} {
		if !strings.Contains(strings.Join(strings.Fields(string(code)), " "), strings.Join(strings.Fields(want), " ")) {
			t.Errorf("generated code lacks %q", want)
		}
	}
	_, err = Generate([]Icon{{DartName: "x", GoName: "not valid", CodePoint: 1}})
	appErr, ok := errors.FromError(err)
	if !ok || !appErr.HasRoute("Generate.IconsFormatFailed") {
		t.Errorf("unexpected error %v", err)
	}
}

func TestRun(t *testing.T) {
	dir := t.TempDir()
	ref := filepath.Join(dir, "ref")
	srcDir := filepath.Join(ref, filepath.Dir(iconsFile))
	if err := os.MkdirAll(srcDir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(ref, iconsFile), []byte(sample), 0o644); err != nil {
		t.Fatal(err)
	}
	out := filepath.Join(dir, "icons_gen.go")
	if err := Run([]string{"-reference", ref, "-out", out}); err != nil {
		t.Fatal(err)
	}
	first, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	if err := Run([]string{"-reference", ref, "-out", out}); err != nil {
		t.Fatal(err)
	}
	second, _ := os.ReadFile(out)
	if string(first) != string(second) {
		t.Error("second run changed the output")
	}

	tests := []struct {
		name  string
		args  []string
		route string
	}{
		{"bad flag", []string{"-nope"}, "Run.IconsBadFlags"},
		{"missing source", []string{"-reference", filepath.Join(dir, "missing")}, "Run.IconsReadFailed"},
		{"unwritable", []string{"-reference", ref, "-out", filepath.Join(dir, "no", "such", "dir", "x.go")}, "Run.IconsWriteFailed"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			err := Run(tt.args)
			appErr, ok := errors.FromError(err)
			if !ok {
				t.Fatalf("expected *errors.Error, got %T (%v)", err, err)
			}
			if !appErr.HasRoute(tt.route) {
				t.Errorf("unexpected failure path: %s", appErr.Route())
			}
		})
	}
}

