func TestRunGeneratesTheWindowsTables(t *testing.T) {
	// The reference directory is named flutter, as in the repository, with VERSION beside it.
	root := t.TempDir()
	ref := filepath.Join(root, "flutter")
	dir := filepath.Join(ref, dataDir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	for name, content := range windowsFiles() {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.WriteFile(filepath.Join(root, "VERSION"), []byte("flutter_commit=abc123\nflutter_version=3.0.1\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	out := filepath.Join(t.TempDir(), "keymap_gen.go")
	if err := Run([]string{"-reference", ref, "-out", "", "-windows-out", out}); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	text := squeeze(string(got))
	for _, want := range []string{
		"// Code generated by glutter-gen keys; DO NOT EDIT.",
		"package windows",
		"commit abc123 (Flutter 3.0.1)",
		"0x1e: 0x70004, // KeyA",
		"0x4f: 0x70059, // Numpad1",
		"0xe01d: 0x700e4, // ControlRight",
		"0x61: 0x200000231, // Numpad1",
		"0x10: 0x200000102, // ShiftLeft",
		"0xa0: 0x200000102, // ShiftLeft",
		"0xa3: 0x200000101, // ControlRight",
		"0x4f: 0x200000231, // Numpad1",
		"0xe01d: 0x200000101, // ControlRight",
		`"LSHIFT": 0xa0,`,
		`"SHIFT": 0x10,`,
		"{scanCode: 0x1e, logical: 0x61, mandatory: true}, // KeyA",
	} {
		if !strings.Contains(text, squeeze(want)) {
			t.Errorf("the output lacks %q:\n%s", want, got)
		}
	}
	for _, not := range []string{"Lang1", "NoUSB", "0x384"} {
		if strings.Contains(text, not) {
			t.Errorf("the output has %q:\n%s", not, got)
		}
	}
	// The file is only written when it changes.
	info1, err := os.Stat(out)
	if err != nil {
		t.Fatal(err)
	}
	if err := Run([]string{"-reference", ref, "-out", "", "-windows-out", out}); err != nil {
		t.Fatal(err)
	}
	info2, err := os.Stat(out)
	if err != nil {
		t.Fatal(err)
	}
	if !info2.ModTime().Equal(info1.ModTime()) {
		t.Error("the second run changed the file")
	}
}

func TestPinnedFlutter(t *testing.T) {
	tests := []struct {
		name, version, want string
		missing             bool
	}{
		{"commit and version", "flutter_commit=abc\nflutter_version=3.1\n", "commit abc (Flutter 3.1)", false},
		{"commit only", "flutter_commit=abc\n", "commit abc", false},
		{"no commit", "flutter_version=3.1\n", "an unpinned checkout", false},
		{"no file", "", "an unpinned checkout", true},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := t.TempDir()
			if !tt.missing {
				if err := os.WriteFile(filepath.Join(root, "VERSION"), []byte(tt.version), 0o644); err != nil {
					t.Fatal(err)
				}
			}
			if got := pinnedFlutter(filepath.Join(root, "flutter")); got != tt.want {
				t.Errorf("pinnedFlutter = %q, want %q", got, tt.want)
			}
		})
	}
}

func TestWindowsFailures(t *testing.T) {
	with := func(kv ...string) map[string]string {
		f := windowsFiles()
		for i := 0; i < len(kv); i += 2 {
			f[kv[i]] = kv[i+1]
		}
		return f
	}
	tests := []struct {
		name  string
		files map[string]string
		tag   string
		route string
	}{
		{"a Windows scan code that is not a number", with("physical_key_data.g.json", `{"KeyA": {"scanCodes": {"usb": 1, "windows": "x"}}}`), "KeysDataInvalid", "generateWindows->physicalKey.scanCode.KeysDataInvalid"},
		{"two physical keys with the same scan code", with("physical_key_data.g.json", `{"KeyA": {"scanCodes": {"usb": 1, "windows": 30}}, "KeyB": {"scanCodes": {"usb": 2, "windows": 30}}}`), "KeysDuplicate", "generateWindows.KeysDuplicate"},
		{"two logical keys with the same virtual key", with("logical_key_data.g.json", `{"KeyA": {"value": 97, "names": {"windows": ["A1"]}, "values": {"windows": [65]}}, "KeyB": {"value": 98, "names": {"windows": ["B1"]}, "values": {"windows": [65]}}}`), "KeysDuplicate", "generateWindows.KeysDuplicate"},
		{"two virtual keys with the same name", with("logical_key_data.g.json", `{"KeyA": {"value": 97, "names": {"windows": ["A1", "A1"]}, "values": {"windows": [65, 66]}}}`), "KeysDuplicate", "generateWindows.KeysDuplicate"},
		{"names and values of different lengths", with("logical_key_data.g.json", `{"KeyA": {"value": 97, "names": {"windows": ["A1"]}, "values": {"windows": [65, 66]}}}`), "KeysDataInvalid", "generateWindows->logicalKey.windowsVirtualKeys.KeysDataInvalid"},
		{"a scan code mapping with an unknown physical key", with("windows_scancode_logical_map.json", `{"Nope": "Numpad1"}`), "KeysGoalUnknown", "generateWindows.KeysGoalUnknown"},
		{"a scan code mapping with an unknown logical key", with("windows_scancode_logical_map.json", `{"Numpad1": "Nope"}`), "KeysGoalUnknown", "generateWindows.KeysGoalUnknown"},
		{"a goal without a Windows scan code", with("layout_goals.json", `{"Lang1": true}`), "KeysGoalUnknown", "generateWindows.KeysGoalUnknown"},
		{"a goal without a logical key", with("layout_goals.json", `{"NoUSB": true}`), "KeysGoalUnknown", "generateWindows.KeysGoalUnknown"},
		{"the scan code file is missing", map[string]string{"physical_key_data.g.json": physicalJSON, "logical_key_data.g.json": logicalJSON, "layout_goals.json": goalsJSON}, "KeysDataMissing", "loadData.KeysDataMissing"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			ref := writeData(t, tt.files)
			err := Run([]string{"-reference", ref, "-out", "", "-windows-out", filepath.Join(t.TempDir(), "out.go")})
			appErr, ok := errors.FromError(err)
			if !ok {
				t.Fatalf("expected *errors.Error, got %T (%v)", err, err)
			}
			if appErr.Tag != tt.tag || !appErr.HasRoute(tt.route) {
				t.Errorf("got %s via %s, want %s via %s", appErr.Tag, appErr.Route(), tt.tag, tt.route)
			}
		})
	}
}

func realReference(t *testing.T) string {
	t.Helper()
	ref := filepath.Join("..", "..", "..", "..", "reference", "flutter")
	if _, err := os.Stat(filepath.Join(ref, dataDir)); err != nil {
		t.Skipf("reference/ is missing, so the tables cannot be regenerated: run scripts/fetch-reference.sh (%v)", err)
	}
	return ref
}

// TestCommittedWindowsTablesAreCurrent regenerates the Windows tables from Flutter's data and
// compares them with the committed file (skipped where reference/ is missing).
func TestCommittedWindowsTablesAreCurrent(t *testing.T) {
	ref := realReference(t)
	out := filepath.Join(t.TempDir(), "keymap_gen.go")
	if err := Run([]string{"-reference", ref, "-out", "", "-windows-out", out}); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	committed, err := os.ReadFile(filepath.Join("..", "..", "..", "..", "internal", "platform", "windows", "keymap_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, committed) {
		t.Error("internal/platform/windows/keymap_gen.go is stale: run go generate ./internal/platform/windows/")
	}
	if !strings.Contains(string(got), "commit abaf9c52") {
		t.Errorf("the header does not name the pinned commit:\n%s", string(got)[:400])
	}
}

// TestEveryKeyOfTheDataIsInAWindowsTable checks, over Flutter's data, that every physical key
// with a Windows scan code and a USB code has a physical entry, every logical key with Windows
// virtual keys has a logical entry for each of them, and that the tables equal the ones of
// flutter_key_map.g.cc, which Flutter generated from the same data (skipped where reference/ is
// missing).
func TestEveryKeyOfTheDataIsInAWindowsTable(t *testing.T) {
	ref := realReference(t)
	src, err := loadData(filepath.Join(ref, dataDir), false, false, true)
	if err != nil {
		t.Fatal(err)
	}
	code, err := generateWindows(src, "test")
	if err != nil {
		t.Fatal(err)
	}
	text := string(code)
	section := func(from, to string) string {
		i := strings.Index(text, from)
		j := strings.Index(text, to)
		if i < 0 || j < i {
			t.Fatalf("the output has no section between %q and %q", from, to)
		}
		return text[i:j]
	}
	physicalSection := section("var scanCodeToPhysical", "var virtualKeyToLogical")
	logicalSection := section("var virtualKeyToLogical", "var scanCodeToLogical")
	scanSection := section("var scanCodeToLogical", "var virtualKeyNames")
	wantPhysical, wantLogical := 0, 0
	for name, k := range src.physical {
		w, hasW, err := k.scanCode(name, "windows")
		if err != nil {
			t.Fatal(err)
		}
		_, hasU, err := k.scanCode(name, "usb")
		if err != nil {
			t.Fatal(err)
		}
		if hasW && hasU {
			wantPhysical++
			if !strings.Contains(physicalSection, "0x"+strconv.FormatUint(w, 16)+":") {
				t.Errorf("physical key %s (scan code %#x) has no entry", name, w)
			}
		}
	}
	for name, k := range src.logical {
		for _, vk := range k.Values["windows"] {
			wantLogical++
			if !strings.Contains(logicalSection, "0x"+strconv.FormatUint(vk, 16)+":") {
				t.Errorf("logical key %s (virtual key %#x) has no entry", name, vk)
			}
		}
	}
	if wantPhysical != 157 || wantLogical != 121 {
		t.Errorf("Flutter's data has %d physical and %d logical Windows keys; flutter_key_map.g.cc has 157 and 121", wantPhysical, wantLogical)
	}
	if !strings.Contains(scanSection, "0xe038: 0x200000105") {
		t.Errorf("the scan code table lacks the right Alt key:\n%s", scanSection)
	}
}
