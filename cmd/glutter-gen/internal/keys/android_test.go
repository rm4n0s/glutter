func TestRunGeneratesTheAndroidTables(t *testing.T) {
	ref := writeData(t, androidFiles())
	out := filepath.Join(t.TempDir(), "keymap_gen.go")
	if err := Run([]string{"-reference", ref, "-out", "", "-android-out", out}); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	text := squeeze(string(got))
	for _, want := range []string{
		"// Code generated by glutter-gen keys; DO NOT EDIT.",
		"package android",
		"30: 0x70004, // KeyA",
		"464: 0x12, // Fn",
		"465: 0x12, // Fn",
		"29: 0x61, // KeyA",
		"115: 0x100000104, // CapsLock",
		"{mask: metaCtrlOn, keys: []keyPair{",
		"{physical: 0x700e1, logical: 0x200000102}, // ShiftLeft",
		"{physical: 0x700e6, logical: 0x200000105}, // AltRight",
		"{mask: metaCapsLockOn, physical: 0x70039, logical: 0x100000104}, // CapsLock",
	} {
		if !strings.Contains(text, squeeze(want)) {
			t.Errorf("the output lacks %q:\n%s", want, got)
		}
	}
	// A key without an Android scan code or without a USB code is not in the table.
	for _, not := range []string{"Lang1", "NoUSB", "900:"} {
		if strings.Contains(text, not) {
			t.Errorf("the output has %q:\n%s", not, got)
		}
	}
	// The file is only written when it changes.
	info1, err := os.Stat(out)
	if err != nil {
		t.Fatal(err)
	}
	if err := Run([]string{"-reference", ref, "-out", "", "-android-out", out}); err != nil {
		t.Fatal(err)
	}
	info2, err := os.Stat(out)
	if err != nil {
		t.Fatal(err)
	}
	if !info2.ModTime().Equal(info1.ModTime()) {
		t.Error("the second run changed the file")
	}
}

func TestAndroidFailures(t *testing.T) {
	with := func(name, content string) map[string]string {
		f := androidFiles()
		f[name] = content
		return f
	}
	tests := []struct {
		name  string
		files map[string]string
		tag   string
		route string
	}{
		{"an android scan code that is not a list", with("physical_key_data.g.json", `{"KeyA": {"scanCodes": {"usb": 1, "android": 30}}}`), "KeysDataInvalid", "generateAndroid->physicalKey.androidScanCodes.KeysDataInvalid"},
		{"a usb code that is not a number", with("physical_key_data.g.json", `{"KeyA": {"scanCodes": {"usb": "x", "android": [30]}}}`), "KeysDataInvalid", "generateAndroid->physicalKey.scanCode.KeysDataInvalid"},
		{"two physical keys with the same scan code", with("physical_key_data.g.json", `{"KeyA": {"scanCodes": {"usb": 1, "android": [30]}}, "KeyB": {"scanCodes": {"usb": 2, "android": [30]}}}`), "KeysDuplicate", "generateAndroid.KeysDuplicate"},
		{"two logical keys with the same key code", with("logical_key_data.g.json", `{"KeyA": {"value": 97, "values": {"android": [29]}}, "KeyB": {"value": 98, "values": {"android": [29]}}}`), "KeysDuplicate", "generateAndroid.KeysDuplicate"},
		{"a goal without a physical key", with("physical_key_data.g.json", `{"KeyA": {"scanCodes": {"usb": 1, "android": [30]}}}`), "KeysGoalUnknown", "generateAndroid.KeysGoalUnknown"},
		{"a goal whose physical key has no USB code", with("physical_key_data.g.json", `{"ControlLeft": {"scanCodes": {"android": [29]}}}`), "KeysGoalUnknown", "generateAndroid.KeysGoalUnknown"},
		{"a goal without a logical key", with("logical_key_data.g.json", `{"KeyA": {"value": 97}}`), "KeysGoalUnknown", "generateAndroid.KeysGoalUnknown"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			ref := writeData(t, tt.files)
			err := Run([]string{"-reference", ref, "-out", "", "-android-out", filepath.Join(t.TempDir(), "out.go")})
			appErr, ok := errors.FromError(err)
			if !ok {
				t.Fatalf("expected *errors.Error, got %T (%v)", err, err)
			}
			if appErr.Tag != tt.tag || !appErr.HasRoute(tt.route) {
				t.Errorf("got %s via %s, want %s via %s", appErr.Tag, appErr.Route(), tt.tag, tt.route)
			}
		})
	}
}

// TestCommittedAndroidTablesAreCurrent regenerates the Android tables from Flutter's data and compares
// them with the committed file (skipped where reference/ is missing).
func TestCommittedAndroidTablesAreCurrent(t *testing.T) {
	ref := filepath.Join("..", "..", "..", "..", "reference", "flutter")
	if _, err := os.Stat(filepath.Join(ref, dataDir)); err != nil {
		t.Skipf("reference/ is missing, so the tables cannot be regenerated: run scripts/fetch-reference.sh (%v)", err)
	}
	out := filepath.Join(t.TempDir(), "keymap_gen.go")
	if err := Run([]string{"-reference", ref, "-out", "", "-android-out", out}); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	committed, err := os.ReadFile(filepath.Join("..", "..", "..", "..", "internal", "platform", "android", "keymap_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, committed) {
		t.Error("internal/platform/android/keymap_gen.go is stale: run go generate ./internal/platform/android/")
	}
}

var javaPut = regexp.MustCompile(`put\((0x[0-9a-fA-F]+)L, (0x[0-9a-fA-F]+)L\);`)

// TestAndroidTablesEqualFlutterKeyboardMap compares the generated tables with the KeyboardMap.java
// that Flutter generated from the same data (skipped where reference/ is missing).
func TestAndroidTablesEqualFlutterKeyboardMap(t *testing.T) {
	ref := filepath.Join("..", "..", "..", "..", "reference", "flutter")
	if _, err := os.Stat(filepath.Join(ref, dataDir)); err != nil {
		t.Skipf("reference/ is missing: run scripts/fetch-reference.sh (%v)", err)
	}
	javaFile := filepath.Join(ref, "engine", "src", "flutter", "shell", "platform", "android", "io", "flutter", "embedding", "android", "KeyboardMap.java")
	java, err := os.ReadFile(javaFile)
	if err != nil {
		t.Skipf("KeyboardMap.java is missing (%v)", err)
	}
	src, err := loadData(filepath.Join(ref, dataDir), false, false, false)
	if err != nil {
		t.Fatal(err)
	}
	code, err := generateAndroid(src)
	if err != nil {
		t.Fatal(err)
	}
	text := string(java)
	split := strings.Index(text, "keyCodeToLogical =")
	end := strings.Index(text, "pressingGoals =")
	if split < 0 || end < split {
		t.Fatal("KeyboardMap.java has an unexpected layout")
	}
	parse := func(section string) map[uint64]uint64 {
		m := map[uint64]uint64{}
		for _, match := range javaPut.FindAllStringSubmatch(section, -1) {
			k, err := strconv.ParseUint(match[1][2:], 16, 64)
			if err != nil {
				t.Fatal(err)
			}
			v, err := strconv.ParseUint(match[2][2:], 16, 64)
			if err != nil {
				t.Fatal(err)
			}
			m[k] = v
		}
		return m
	}
	for _, c := range []struct {
		name    string
		java    map[uint64]uint64
		goTable string
	}{
		{"scanCodeToPhysical", parse(text[:split]), "scanCodeToPhysical"},
		{"keyCodeToLogical", parse(text[split:end]), "keyCodeToLogical"},
	} {
		if len(c.java) < 100 {
			t.Fatalf("%s: the parse of KeyboardMap.java found only %d entries", c.name, len(c.java))
		}
		table := tableOf(string(code), c.goTable)
		if len(table) != len(c.java) {
			t.Errorf("%s: %d entries, KeyboardMap.java has %d", c.name, len(table), len(c.java))
		}
		for k, v := range c.java {
			if got, ok := table[k]; !ok || got != v {
				t.Errorf("%s[%d] = %#x (present %v), KeyboardMap.java has %#x", c.name, k, got, ok, v)
			}
		}
	}
}

var goEntry = regexp.MustCompile(`(?m)^\s*(\d+):\s+(0x[0-9a-f]+),`)

// tableOf reads the entries of the map called name from generated Go code.
func tableOf(code, name string) map[uint64]uint64 {
	start := strings.Index(code, "var "+name+" =")
	rest := code[start:]
	rest = rest[:strings.Index(rest, "\n}\n")]
	m := map[uint64]uint64{}
	for _, match := range goEntry.FindAllStringSubmatch(rest, -1) {
		k, _ := strconv.ParseUint(match[1], 10, 64)
		v, _ := strconv.ParseUint(match[2][2:], 16, 64)
		m[k] = v
	}
	return m
}
