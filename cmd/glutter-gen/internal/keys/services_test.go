func servicesFiles() map[string]string {
	files := validFiles()
	files["physical_key_data.g.json"] = `{
  "KeyB": {"scanCodes": {"usb": 458757, "xkb": 56}},
  "KeyA": {"scanCodes": {"usb": 458756, "xkb": 38}},
  "Super": {"scanCodes": {"usb": 17}},
  "Fn": {"scanCodes": {"xkb": 1}}
}`
	files["logical_key_data.g.json"] = `{
  "KeyA": {"name": "KeyA", "value": 97},
  "ShiftLeft": {"name": "ShiftLeft", "value": 8589934850},
  "ShiftRight": {"name": "ShiftRight", "value": 8589934851},
  "Shift": {"name": "Shift", "value": 8589935090}
}`
	files["synonyms.json"] = `{"Shift": ["ShiftLeft", "ShiftRight"]}`
	return files
}

func TestRunGeneratesTheServicesKeys(t *testing.T) {
	ref := writeData(t, servicesFiles())
	out := filepath.Join(t.TempDir(), "keyboard_key_gen.go")
	if err := Run([]string{"-reference", ref, "-out", "", "-services-out", out}); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	text := squeeze(string(got))
	for _, want := range []string{
		"// Code generated by glutter-gen keys; DO NOT EDIT.",
		"package services",
		`// LogicalKeyboardKeyKeyA is the logical "Key A" key on the keyboard.`,
		"// Flutter: services/keyboard_key.g.dart LogicalKeyboardKey.keyA",
		"LogicalKeyboardKeyKeyA LogicalKeyboardKey = 0x61",
		"LogicalKeyboardKeyShiftLeft LogicalKeyboardKey = 0x200000102",
		"LogicalKeyboardKeyShiftLeft: LogicalKeyboardKeyShift,",
		"LogicalKeyboardKeyShift: {LogicalKeyboardKeyShiftLeft, LogicalKeyboardKeyShiftRight},",
		"PhysicalKeyboardKeyKeyA PhysicalKeyboardKey = 0x00070004",
		`PhysicalKeyboardKeySuper: "Super Key",`,
		"// Flutter: services/keyboard_key.g.dart PhysicalKeyboardKey.superKey",
	} {
		if !strings.Contains(text, squeeze(want)) {
			t.Errorf("the output lacks %q:\n%s", want, got)
		}
	}
	// A physical key without a USB usage (Fn here has only an XKB code) has no
	// constant, and the keys are in the order of their ids.
	if strings.Contains(text, "PhysicalKeyboardKeyFn") {
		t.Error("a key without a USB usage got a constant")
	}
	if strings.Index(text, "PhysicalKeyboardKeySuper PhysicalKeyboardKey") > strings.Index(text, "PhysicalKeyboardKeyKeyA PhysicalKeyboardKey") {
		t.Error("the physical keys are not in the order of their usages")
	}
}

func TestServicesKeyFailures(t *testing.T) {
	with := func(name, content string) map[string]string {
		files := servicesFiles()
		files[name] = content
		return files
	}
	tests := []struct {
		name  string
		files map[string]string
		tag   string
		route string
	}{
		{"synonyms missing", func() map[string]string { f := servicesFiles(); delete(f, "synonyms.json"); return f }(), "KeysDataMissing", "loadData.KeysDataMissing"},
		{"synonym of an unknown key", with("synonyms.json", `{"Shift": ["ShiftLeft", "Nope"]}`), "KeysSynonymUnknown", "generateServices.KeysSynonymUnknown"},
		{"unknown pseudo-key", with("synonyms.json", `{"Nope": ["ShiftLeft"]}`), "KeysSynonymUnknown", "generateServices.KeysSynonymUnknown"},
		{
			"two logical keys with the same value",
			with("logical_key_data.g.json", `{"KeyA": {"name": "KeyA", "value": 97}, "KeyB": {"name": "KeyB", "value": 97}, "Shift": {"name": "Shift", "value": 1}, "ShiftLeft": {"name": "ShiftLeft", "value": 2}, "ShiftRight": {"name": "ShiftRight", "value": 3}}`),
			"KeysDuplicate", "generateServices.KeysDuplicate",
		},
		{
			"two physical keys with the same usage",
			with("physical_key_data.g.json", `{"KeyA": {"scanCodes": {"usb": 5}}, "KeyB": {"scanCodes": {"usb": 5}}}`),
			"KeysDuplicate", "generateServices.KeysDuplicate",
		},
		{
			"a USB usage that is not a number",
			with("physical_key_data.g.json", `{"KeyA": {"scanCodes": {"usb": "x"}}}`),
			"KeysDataInvalid", "generateServices->physicalKey.scanCode.KeysDataInvalid",
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			ref := writeData(t, tc.files)
			err := Run([]string{"-reference", ref, "-out", "", "-services-out", filepath.Join(t.TempDir(), "out.go")})
			appErr, ok := errors.FromError(err)
			if !ok {
				t.Fatalf("expected *errors.Error, got %T (%v)", err, err)
			}
			if appErr.Tag != tc.tag || !appErr.HasRoute(tc.route) {
				t.Errorf("got %s via %s, want %s via %s", appErr.Tag, appErr.Route(), tc.tag, tc.route)
			}
		})
	}
}
