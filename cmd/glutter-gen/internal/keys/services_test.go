func TestSplitName(t *testing.T) {
	tests := []struct{ in, want string }{
		{"KeyA", "Key A"},
		{"ShiftLeft", "Shift Left"},
		{"Digit1", "Digit 1"},
		{"F1", "F1"},
		{"F12", "F12"},
		{"Numpad0", "Numpad 0"},
		{"TVInput", "TV Input"},
		{"AVRPower", "AVR Power"},
		{"TV3DMode", "TV 3 D Mode"},
		{"TVInputHDMI1", "TV Input HDMI 1"},
		{"ColorF0Red", "Color F0 Red"},
		{"PInPDown", "P In P Down"},
		{"Space", "Space"},
	}
	for _, tc := range tests {
		t.Run(tc.in, func(t *testing.T) {
			if got := splitName(tc.in); got != tc.want {
				t.Errorf("splitName(%q) = %q, want %q", tc.in, got, tc.want)
			}
		})
	}
}

