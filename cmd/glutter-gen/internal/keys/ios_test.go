func iosFiles() map[string]string {
	f := validFiles()
	f["physical_key_data.g.json"] = `{
  "KeyA":  {"scanCodes": {"usb": 458756, "ios": 4}},
  "Enter": {"scanCodes": {"usb": 458792, "ios": 40}},
  "F1":    {"scanCodes": {"usb": 458810, "ios": 58}},
  "F12":   {"scanCodes": {"usb": 458821, "ios": 69}},
  "NoIOS": {"scanCodes": {"usb": 900}},
  "NoUSB": {"scanCodes": {"ios": 900}}
}`
	f["logical_key_data.g.json"] = `{
  "KeyA":  {"value": 97},
  "Enter": {"value": 4294967309, "names": {"ios": ["Enter"]}, "values": {"ios": [40]}}
}`
	return f
}

func TestRunGeneratesTheIOSTables(t *testing.T) {
	ref := writeFlutter(t, iosFiles())
	out := filepath.Join(t.TempDir(), "keymap_gen.go")
	if err := Run([]string{"-reference", ref, "-out", "", "-ios-out", out}); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	text := squeeze(string(got))
	for _, want := range []string{
		"// Code generated by glutter-gen keys; DO NOT EDIT.",
		"commit abc123 (Flutter 3.0.1)",
		"package ios",
		"var keyCodeToPhysicalKey = map[uint32]uint64{",
		"0x4: 0x70004, // KeyA",
		"0x28: 0x70028, // Enter",
		"var keyCodeToLogicalKey = map[uint32]uint64{",
		"0x28: 0x10000000d, // Enter",
		"var functionKeyCodes = map[uint32]bool{",
		"0x3a: true, // F1",
		"0x45: true, // F12",
	} {
		if !strings.Contains(text, squeeze(want)) {
			t.Errorf("the iOS tables lack %q:\n%s", want, got)
		}
	}
	if strings.Contains(text, "NoIOS") || strings.Contains(text, "NoUSB") {
		t.Error("a key with no iOS key code or no USB usage is in the tables")
	}
	if strings.Contains(text, "true, // Enter") || strings.Contains(text, "true, // KeyA") {
		t.Error("a key that is not a function key is in functionKeyCodes")
	}
}

func TestIOSErrors(t *testing.T) {
	for _, tt := range []struct {
		name   string
		mutate func(f map[string]string)
	}{
		{"two physical keys share a key code", func(f map[string]string) {
			f["physical_key_data.g.json"] = `{"A": {"scanCodes": {"usb": 1, "ios": 5}}, "B": {"scanCodes": {"usb": 2, "ios": 5}}}`
		}},
		{"two logical keys share a key code", func(f map[string]string) {
			f["logical_key_data.g.json"] = `{"A": {"value": 1, "values": {"ios": [5]}}, "B": {"value": 2, "values": {"ios": [5]}}}`
		}},
	} {
		t.Run(tt.name, func(t *testing.T) {
			files := iosFiles()
			tt.mutate(files)
			ref := writeFlutter(t, files)
			err := Run([]string{"-reference", ref, "-out", "", "-ios-out", filepath.Join(t.TempDir(), "x.go")})
			appErr, ok := errors.FromError(err)
			if !ok || appErr.Tag != tagKeysDuplicate || !appErr.HasRoute("generateIOS.KeysDuplicate") {
				t.Fatalf("err = %v (route %v), want KeysDuplicate via generateIOS", err, errRoute(err))
			}
		})
	}
}

// TestIOSTablesMatchFlutterOwnGeneratedFile compares the tables with the KeyCodeMap.g.mm that Flutter generated from the same data:
// every key code, physical key, logical key and function key must be there with the same values. It needs the reference checkout of
// scripts/fetch-reference.sh.
func TestIOSTablesMatchFlutterOwnGeneratedFile(t *testing.T) {
	const ref = "../../../../reference/flutter"
	mm, err := os.ReadFile(filepath.Join(ref, "engine/src/flutter/shell/platform/darwin/ios/framework/Source/KeyCodeMap.g.mm"))
	if err != nil {
		t.Skip("no reference checkout with the iOS embedder: run scripts/fetch-reference.sh")
	}
	src, err := loadData(filepath.Join(ref, dataDir), false, false, false)
	if err != nil {
		t.Skip("no key data in the reference checkout")
	}
	out, err := generateIOS(src, "test")
	if err != nil {
		t.Fatal(err)
	}
	section := func(text, start string) string {
		i := strings.Index(text, start)
		if i < 0 {
			t.Fatalf("no %q", start)
		}
		j := strings.Index(text[i:], "\n}")
		return text[i : i+j]
	}
	parse := func(re *regexp.Regexp, sec string) map[uint64]uint64 {
		m := map[uint64]uint64{}
		for _, e := range re.FindAllStringSubmatch(sec, -1) {
			k, _ := strconv.ParseUint(e[1], 16, 64)
			v := uint64(1)
			if len(e) > 2 && e[2] != "" {
				v, _ = strconv.ParseUint(e[2], 16, 64)
			}
			m[k] = v
		}
		return m
	}
	mmPair := regexp.MustCompile(`\{0x([0-9a-f]+), 0x([0-9a-f]+)\}`)
	goPair := regexp.MustCompile(`0x([0-9a-f]+): +0x([0-9a-f]+),`)
	for _, tc := range []struct{ goName, mmName string }{
		{"keyCodeToPhysicalKey", "const std::map<uint32_t, uint64_t> keyCodeToPhysicalKey"},
		{"keyCodeToLogicalKey", "const std::map<uint32_t, uint64_t> keyCodeToLogicalKey"},
	} {
		want := parse(mmPair, section(string(mm), tc.mmName))
		got := parse(goPair, section(string(out), "var "+tc.goName))
		if len(want) == 0 || len(got) != len(want) {
			t.Errorf("%s has %d entries, Flutter's has %d", tc.goName, len(got), len(want))
		}
		for k, v := range want {
			if got[k] != v {
				t.Errorf("%s[0x%x] = 0x%x, Flutter's is 0x%x", tc.goName, k, got[k], v)
			}
		}
	}
	wantF := parse(regexp.MustCompile(`0x([0-9a-f]+),`), section(string(mm), "const std::set<uint32_t> functionKeyCodes"))
	gotF := parse(regexp.MustCompile(`0x([0-9a-f]+): +true,`), section(string(out), "var functionKeyCodes"))
	if len(wantF) == 0 || len(gotF) != len(wantF) {
		t.Errorf("functionKeyCodes has %d entries, Flutter's has %d", len(gotF), len(wantF))
	}
	for k := range wantF {
		if _, ok := gotF[k]; !ok {
			t.Errorf("function key 0x%x is missing", k)
		}
	}
}
