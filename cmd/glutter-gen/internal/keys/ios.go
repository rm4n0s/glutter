package keys

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"

	"github.com/rm4n0s/errors"
)

// generateIOS writes the tables of the iOS platform: the physical key of each key code (keyCodeToPhysicalKey), the logical key of
// the key codes that the characters of a press do not decide (keyCodeToLogicalKey), and the key codes of the function keys
// (functionKeyCodes). It ports ios_key_code_map_mm.tmpl of dev/tools/gen_keycodes, whose output is KeyCodeMap.g.mm. The key code of
// iOS is UIKeyboardHIDUsage, the USB HID usage. The tables of the modifier flags, the special keys and the plane constants are fixed
// numbers of the embedder, kept by hand in keyboard.go.
func generateIOS(d *data, pinned string) ([]byte, error) {
	physical := map[uint64]uint64{}
	physicalOwner := map[uint64]string{}
	function := map[uint64]string{}
	for _, name := range sortedKeys(d.physical) {
		k := d.physical[name]
		code, hasCode, err := k.scanCode(name, "ios")
		if err != nil {
			return nil, err
		}
		usb, hasUSB, err := k.scanCode(name, "usb")
		if err != nil {
			return nil, err
		}
		if !hasCode || !hasUSB {
			continue
		}
		if prev, dup := physicalOwner[code]; dup {
			return nil, errors.New(tagKeysDuplicate, "two physical keys share an iOS key code", "keyCode", code, "keys", []string{prev, name})
		}
		physicalOwner[code] = name
		physical[code] = usb
		if n, err := strconv.Atoi(name[1:]); name[0] == 'F' && len(name) > 1 && err == nil && n >= 1 && n <= 24 {
			function[code] = name
		}
	}
	logical := map[uint64]uint64{}
	logicalOwner := map[uint64]string{}
	for _, name := range sortedKeys(d.logical) {
		k := d.logical[name]
		for _, code := range k.Values["ios"] {
			if prev, dup := logicalOwner[code]; dup {
				return nil, errors.New(tagKeysDuplicate, "two logical keys share an iOS key code", "keyCode", code, "keys", []string{prev, name})
			}
			logicalOwner[code] = name
			logical[code] = k.Value
		}
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by glutter-gen keys; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Source: Flutter's dev/tools/gen_keycodes/data, %s:\n", pinned)
	b.WriteString("// physical_key_data.g.json and logical_key_data.g.json, the content of ios_key_code_map_mm.tmpl.\n")
	b.WriteString("// Flutter is BSD-3-Clause licensed; see third_party/flutter/LICENSE.\n\n")
	b.WriteString("package ios\n\n")
	b.WriteString("// keyCodeToPhysicalKey maps UIKey.keyCode (UIKeyboardHIDUsage) to the id of Flutter's PhysicalKeyboardKey (the USB HID\n")
	b.WriteString("// usage). iOS has no scan code, only this virtual key code of the physical key.\n//\n")
	b.WriteString("// Flutter: engine/src/flutter/shell/platform/darwin/ios/framework/Source/KeyCodeMap.g.mm keyCodeToPhysicalKey\n")
	b.WriteString("var keyCodeToPhysicalKey = map[uint32]uint64{\n")
	for _, c := range sortedUint64(physical) {
		fmt.Fprintf(&b, "\t0x%x: 0x%x, // %s\n", c, physical[c], physicalOwner[c])
	}
	b.WriteString("}\n\n")
	b.WriteString("// keyCodeToLogicalKey maps UIKey.keyCode to the id of Flutter's LogicalKeyboardKey for the keys that can't or shouldn't be\n")
	b.WriteString("// derived from the characters of the press (the function keys, the modifiers, Enter, Escape, Backspace, Tab, CapsLock).\n//\n")
	b.WriteString("// Flutter: engine/src/flutter/shell/platform/darwin/ios/framework/Source/KeyCodeMap.g.mm keyCodeToLogicalKey\n")
	b.WriteString("var keyCodeToLogicalKey = map[uint32]uint64{\n")
	for _, c := range sortedUint64(logical) {
		fmt.Fprintf(&b, "\t0x%x: 0x%x, // %s\n", c, logical[c], logicalOwner[c])
	}
	b.WriteString("}\n\n")
	b.WriteString("// functionKeyCodes are the key codes of the function keys, whose characters are not used.\n//\n")
	b.WriteString("// Flutter: engine/src/flutter/shell/platform/darwin/ios/framework/Source/KeyCodeMap.g.mm functionKeyCodes\n")
	b.WriteString("var functionKeyCodes = map[uint32]bool{\n")
	for _, c := range sortedUint64(function) {
		fmt.Fprintf(&b, "\t0x%x: true, // %s\n", c, function[c])
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, errors.NewErr(tagKeysFormatFailed, err)
	}
	return out, nil
}
