// writeData writes a Flutter data directory with the given files and returns the
// reference directory that holds it.
func writeData(t *testing.T, files map[string]string) string {
	t.Helper()
	ref := t.TempDir()
	dir := filepath.Join(ref, dataDir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return ref
}

const (
	physicalJSON = `{
  "KeyB": {"scanCodes": {"usb": 458757, "xkb": 56}},
  "KeyA": {"scanCodes": {"usb": 458756, "xkb": 38, "linux": 30}},
  "Fn":   {"scanCodes": {"usb": 18}}
}`
	logicalJSON = `{
  "KeyA":  {"value": 97, "values": {"android": [29]}},
  "KeyB":  {"value": 98},
  "Enter": {"value": 4294967309, "values": {"gtk": [65293, 65076]}},
  "Shift": {"value": 8589934850, "values": {"gtk": [65505]}}
}`
	goalsJSON = `{"KeyB": false, "KeyA": true}`
)

func validFiles() map[string]string {
	return map[string]string{
		"physical_key_data.g.json": physicalJSON,
		"logical_key_data.g.json":  logicalJSON,
		"layout_goals.json":        goalsJSON,
	}
}

func TestRunGeneratesTheTables(t *testing.T) {
	ref := writeData(t, validFiles())
	out := filepath.Join(t.TempDir(), "keymap_gen.go")
	if err := Run([]string{"-reference", ref, "-out", out}); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	text := string(got)
	for _, want := range []string{
		"// Code generated by glutter-gen keys; DO NOT EDIT.",
		"package linux",
		"38: 0x70004, // KeyA",
		"56: 0x70005, // KeyB",
		"0xff0d:     0x10000000d, // Enter",
		"0xfe34:     0x10000000d, // Enter",
		"0xffe1:     0x200000102, // Shift",
		"{xkbKeycode: 38, logical: 0x61, mandatory: true}, // KeyA",
		"{xkbKeycode: 56, logical: 0x62, mandatory: false}, // KeyB",
	} {
		// gofmt aligns the columns, so compare without runs of spaces.
		if !strings.Contains(squeeze(text), squeeze(want)) {
			t.Errorf("the output lacks %q:\n%s", want, text)
		}
	}
	// Keys without an XKB code (Fn) are not in the physical table, and a keyval
	// that is not GTK's (android 29) is not in the logical one.
	if strings.Contains(text, "Fn") || strings.Contains(text, "0x1d:") {
		t.Errorf("the output has entries it should not:\n%s", text)
	}
	// A second run leaves the file alone.
	info1, err := os.Stat(out)
	if err != nil {
		t.Fatal(err)
	}
	if err := Run([]string{"-reference", ref, "-out", out}); err != nil {
		t.Fatal(err)
	}
	again, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	info2, err := os.Stat(out)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, again) || !info2.ModTime().Equal(info1.ModTime()) {
		t.Error("the second run changed the file")
	}
}

func squeeze(s string) string { return strings.Join(strings.Fields(s), " ") }

func TestFailures(t *testing.T) {
	with := func(name, content string) map[string]string {
		f := validFiles()
		f[name] = content
		return f
	}
	tests := []struct {
		name  string
		files map[string]string
		args  []string
		tag   string
		route string
	}{
		{name: "bad flag", args: []string{"-nope"}, tag: "KeysBadFlags", route: "Run.KeysBadFlags"},
		{name: "no data", files: map[string]string{}, tag: "KeysDataMissing", route: "Run->loadData.KeysDataMissing"},
		{name: "invalid JSON", files: with("layout_goals.json", "{"), tag: "KeysDataInvalid", route: "loadData.KeysDataInvalid"},
		{name: "a scan code that is not a number", files: with("physical_key_data.g.json", `{"KeyA": {"scanCodes": {"usb": "x", "xkb": 38}}}`), tag: "KeysDataInvalid", route: "generate->physicalKey.scanCode.KeysDataInvalid"},
		{
			name:  "two keys with the same XKB code",
			files: with("physical_key_data.g.json", `{"KeyA": {"scanCodes": {"usb": 1, "xkb": 38}}, "KeyB": {"scanCodes": {"usb": 2, "xkb": 38}}}`),
			tag:   "KeysDuplicate", route: "generate.KeysDuplicate",
		},
		{
			name:  "two logical keys with the same keyval",
			files: with("logical_key_data.g.json", `{"KeyA": {"value": 97, "values": {"gtk": [5]}}, "KeyB": {"value": 98, "values": {"gtk": [5]}}}`),
			tag:   "KeysDuplicate", route: "generate.KeysDuplicate",
		},
		{name: "a goal without an XKB code", files: with("layout_goals.json", `{"Fn": true}`), tag: "KeysGoalUnknown", route: "generate.KeysGoalUnknown"},
		{name: "a goal without a logical key", files: with("logical_key_data.g.json", `{"KeyA": {"value": 97}}`), tag: "KeysGoalUnknown", route: "generate.KeysGoalUnknown"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			ref := ""
			if tt.files != nil {
				ref = writeData(t, tt.files)
			} else {
				ref = writeData(t, validFiles())
			}
			args := append([]string{"-reference", ref, "-out", filepath.Join(t.TempDir(), "out.go")}, tt.args...)
			if tt.args != nil {
				args = tt.args
			}
			err := Run(args)
			appErr, ok := errors.FromError(err)
			if !ok {
				t.Fatalf("expected *errors.Error, got %T (%v)", err, err)
			}
			if appErr.Tag != tt.tag || !appErr.HasRoute(tt.route) {
				t.Errorf("got %s via %s, want %s via %s", appErr.Tag, appErr.Route(), tt.tag, tt.route)
			}
		})
	}

	t.Run("a missing data file names the fix", func(t *testing.T) {
		err := Run([]string{"-reference", t.TempDir()})
		appErr, ok := errors.FromError(err)
		if !ok || appErr.Metadata["hint"] != "run scripts/fetch-reference.sh" {
			t.Errorf("error = %v, want a hint to run scripts/fetch-reference.sh", err)
		}
	})
	t.Run("the output cannot be written", func(t *testing.T) {
		ref := writeData(t, validFiles())
		err := Run([]string{"-reference", ref, "-out", filepath.Join(t.TempDir(), "missing-dir", "out.go")})
		appErr, ok := errors.FromError(err)
		if !ok || appErr.Tag != tagKeysWriteFailed || !appErr.HasRoute("Run->writeIfChanged.KeysWriteFailed") {
			t.Errorf("error = %v, want KeysWriteFailed via Run", err)
		}
	})
}

// TestCommittedTablesAreCurrent regenerates the tables from Flutter's data and
// compares them with the committed file. It needs reference/ (git-ignored;
// scripts/fetch-reference.sh creates it), so it is skipped where that is missing.
func TestCommittedTablesAreCurrent(t *testing.T) {
	ref := filepath.Join("..", "..", "..", "..", "reference", "flutter")
	if _, err := os.Stat(filepath.Join(ref, dataDir)); err != nil {
		t.Skipf("reference/ is missing, so the tables cannot be regenerated: run scripts/fetch-reference.sh (%v)", err)
	}
	out := filepath.Join(t.TempDir(), "keymap_gen.go")
	if err := Run([]string{"-reference", ref, "-out", out}); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	committed, err := os.ReadFile(filepath.Join("..", "..", "..", "..", "internal", "platform", "linux", "keymap_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, committed) {
		t.Error("internal/platform/linux/keymap_gen.go is stale: run go generate ./internal/platform/linux/")
	}
}

