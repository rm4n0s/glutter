package keys

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"

	"github.com/rm4n0s/errors"
)

// generateMacOS writes the tables of the macOS platform: the physical key of each key code
// (keyCodeToPhysicalKey), the logical key of the key codes that the characters of an event do not decide
// (keyCodeToLogicalKey), and the layout goals with their key codes. It ports macos_key_code_map_cc.tmpl of
// dev/tools/gen_keycodes, whose output is KeyCodeMap.g.mm. The tables of the modifier flags and the
// plane constants are fixed numbers of the embedder, kept by hand in keyboard.go.
func generateMacOS(d *data, pinned string) ([]byte, error) {
	// macOS key code -> physical key (the USB HID usage Flutter uses as the id).
	physical := map[uint64]uint64{}
	physicalOwner := map[uint64]string{}
	codeOf := map[string]uint64{}
	for _, name := range sortedKeys(d.physical) {
		k := d.physical[name]
		code, hasCode, err := k.scanCode(name, "macos")
		if err != nil {
			return nil, err
		}
		usb, hasUSB, err := k.scanCode(name, "usb")
		if err != nil {
			return nil, err
		}
		if !hasCode || !hasUSB {
			continue
		}
		if prev, dup := physicalOwner[code]; dup {
			return nil, errors.New(tagKeysDuplicate, "two physical keys share a macOS key code",
				"keyCode", code, "keys", []string{prev, name})
		}
		physicalOwner[code] = name
		physical[code] = usb
		codeOf[name] = code
	}

	// macOS key code -> logical key, for the keys that are not characters.
	logical := map[uint64]uint64{}
	logicalOwner := map[uint64]string{}
	for _, name := range sortedKeys(d.logical) {
		k := d.logical[name]
		for _, code := range k.Values["macos"] {
			if prev, dup := logicalOwner[code]; dup {
				return nil, errors.New(tagKeysDuplicate, "two logical keys share a macOS key code",
					"keyCode", code, "keys", []string{prev, name})
			}
			logicalOwner[code] = name
			logical[code] = k.Value
		}
	}

	// The layout goals, by the Unicode value of the logical key as Flutter lists them.
	var goals []goal
	for _, name := range sortedKeys(d.goals) {
		code, ok := codeOf[name]
		if !ok {
			return nil, errors.New(tagKeysGoalUnknown, "a layout goal names a physical key with no macOS key code", "key", name)
		}
		l, ok := d.logical[name]
		if !ok {
			return nil, errors.New(tagKeysGoalUnknown, "a layout goal names a key that has no logical key", "key", name)
		}
		goals = append(goals, goal{name, code, l.Value, d.goals[name]})
	}
	sort.Slice(goals, func(i, j int) bool { return goals[i].logical < goals[j].logical })

	var b bytes.Buffer
	b.WriteString("// Code generated by glutter-gen keys; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Source: Flutter's dev/tools/gen_keycodes/data, %s:\n", pinned)
	b.WriteString("// physical_key_data.g.json, logical_key_data.g.json and layout_goals.json, the content of\n")
	b.WriteString("// macos_key_code_map_cc.tmpl. Flutter is BSD-3-Clause licensed; see third_party/flutter/LICENSE.\n\n")
	b.WriteString("package macos\n\n")

	b.WriteString("// keyCodeToPhysicalKey maps NSEvent.keyCode to the id of Flutter's PhysicalKeyboardKey (the USB HID\n")
	b.WriteString("// usage). macOS has no scan code, only this virtual key code of the physical key.\n//\n")
	b.WriteString("// Flutter: engine/src/flutter/shell/platform/darwin/macos/framework/Source/KeyCodeMap.g.mm keyCodeToPhysicalKey\n")
	b.WriteString("var keyCodeToPhysicalKey = map[uint16]uint64{\n")
	for _, c := range sortedUint64(physical) {
		fmt.Fprintf(&b, "\t0x%x: 0x%x, // %s\n", c, physical[c], physicalOwner[c])
	}
	b.WriteString("}\n\n")

	b.WriteString("// keyCodeToLogicalKey maps NSEvent.keyCode to the id of Flutter's LogicalKeyboardKey for the keys that\n")
	b.WriteString("// can't or shouldn't be derived from the characters of the event (the function keys, the arrows, the\n")
	b.WriteString("// modifiers, the numpad).\n//\n")
	b.WriteString("// Flutter: engine/src/flutter/shell/platform/darwin/macos/framework/Source/KeyCodeMap.g.mm keyCodeToLogicalKey\n")
	b.WriteString("var keyCodeToLogicalKey = map[uint16]uint64{\n")
	for _, c := range sortedUint64(logical) {
		fmt.Fprintf(&b, "\t0x%x: 0x%x, // %s\n", c, logical[c], logicalOwner[c])
	}
	b.WriteString("}\n\n")

	b.WriteString("// layoutGoals lists the keys whose logical key must not depend on the layout, so that shortcuts work on\n")
	b.WriteString("// every layout: a layout that has no Latin character on one of them gives it the logical key of the\n")
	b.WriteString("// US layout when the goal is mandatory.\n//\n")
	b.WriteString("// Flutter: engine/src/flutter/shell/platform/darwin/macos/framework/Source/KeyCodeMap.g.mm kLayoutGoals\n")
	b.WriteString("var layoutGoals = []layoutGoal{\n")
	for _, g := range goals {
		fmt.Fprintf(&b, "\t{keyCode: 0x%x, logical: 0x%x, mandatory: %t}, // %s\n", g.xkb, g.logical, g.mandatory, g.name)
	}
	b.WriteString("}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, errors.NewErr(tagKeysFormatFailed, err)
	}
	return out, nil
}
