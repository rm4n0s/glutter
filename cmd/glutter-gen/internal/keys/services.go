package keys

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"
	"unicode"

	"github.com/rm4n0s/errors"
)

// physicalLabelOverrides are the physical keys whose debug name is not the
// split of their name: Flutter renames the constants that clash with Dart words
// (superKey, newKey), and splits the digit of the launch keys differently.
var physicalLabelOverrides = map[string]string{
	"Super":      "Super Key",
	"New":        "New Key",
	"LaunchApp1": "Launch App1",
	"LaunchApp2": "Launch App2",
}

// dartConstantNames are the logical keys whose Dart constant is not the lower
// camel case of their name, because the name is a Dart word.
var dartConstantNames = map[string]string{"Super": "superKey", "New": "newKey"}

// splitName splits a key name into words for its label: "ShiftLeft" is "Shift
// Left", "TVInput" is "TV Input", "Digit1" is "Digit 1" and "F1" stays "F1".
func splitName(n string) string {
	rs := []rune(n)
	var b strings.Builder
	for i, c := range rs {
		if i > 0 {
			p := rs[i-1]
			var next rune
			if i+1 < len(rs) {
				next = rs[i+1]
			}
			split := false
			switch {
			case unicode.IsLower(p) && unicode.IsUpper(c):
				split = true
			case unicode.IsUpper(p) && unicode.IsUpper(c) && unicode.IsLower(next):
				split = true
			case unicode.IsDigit(p) && unicode.IsUpper(c):
				split = true
			case unicode.IsDigit(c) && (unicode.IsLower(p) || (unicode.IsUpper(p) && i >= 2 && unicode.IsUpper(rs[i-2]))):
				split = true
			}
			if split {
				b.WriteByte(' ')
			}
		}
		b.WriteRune(c)
	}
	return b.String()
}

// dartName is the name of the Dart constant of a key: the name with its leading
// capitals in lower case ("KeyA" is "keyA", "TVInput" is "tvInput").
func dartName(n string) string {
	if renamed, ok := dartConstantNames[n]; ok {
		return renamed
	}
	rs := []rune(n)
	run := 0
	for run < len(rs) && unicode.IsUpper(rs[run]) {
		run++
	}
	if run > 1 && run < len(rs) && unicode.IsLower(rs[run]) {
		run-- // the last capital starts the next word
	}
	if run == 0 {
		run = 1
	}
	return strings.ToLower(string(rs[:run])) + string(rs[run:])
}

type logicalEntry struct {
	name  string
	value uint64
	label string
}

type physicalEntry struct {
	name  string
	usb   uint64
	label string
}

// generateServices writes the key constants and tables of package services.
func generateServices(d *data) ([]byte, error) {
	var logical []logicalEntry
	for _, name := range sortedKeys(d.logical) {
		k := d.logical[name]
		logical = append(logical, logicalEntry{name, k.Value, splitName(name)})
	}
	sort.SliceStable(logical, func(i, j int) bool { return logical[i].value < logical[j].value })
	for i := 1; i < len(logical); i++ {
		if logical[i].value == logical[i-1].value {
			return nil, errors.New(tagKeysDuplicate, "two logical keys share a value", "value", logical[i].value,
				"keys", []string{logical[i-1].name, logical[i].name})
		}
	}
	var physical []physicalEntry
	for _, name := range sortedKeys(d.physical) {
		k := d.physical[name]
		usb, ok, err := k.scanCode(name, "usb")
		if err != nil {
			return nil, err
		}
		if !ok {
			continue
		}
		label, overridden := physicalLabelOverrides[name]
		if !overridden {
			label = splitName(name)
		}
		physical = append(physical, physicalEntry{name, usb, label})
	}
	sort.SliceStable(physical, func(i, j int) bool { return physical[i].usb < physical[j].usb })
	for i := 1; i < len(physical); i++ {
		if physical[i].usb == physical[i-1].usb {
			return nil, errors.New(tagKeysDuplicate, "two physical keys share a USB usage", "usage", physical[i].usb,
				"keys", []string{physical[i-1].name, physical[i].name})
		}
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by glutter-gen keys; DO NOT EDIT.\n")
	b.WriteString("// Source: Flutter's dev/tools/gen_keycodes/data (physical_key_data.g.json,\n")
	b.WriteString("// logical_key_data.g.json, synonyms.json). Flutter is BSD-3-Clause licensed;\n")
	b.WriteString("// see third_party/flutter/LICENSE.\n\n")
	b.WriteString("package services\n\n")

	b.WriteString("// The logical keys, in the order of their ids.\nconst (\n")
	for _, k := range logical {
		fmt.Fprintf(&b, "\t// LogicalKeyboardKey%s is the logical %q key on the keyboard.\n\t//\n", k.name, k.label)
		fmt.Fprintf(&b, "\t// Flutter: services/keyboard_key.g.dart LogicalKeyboardKey.%s\n", dartName(k.name))
		fmt.Fprintf(&b, "\tLogicalKeyboardKey%s LogicalKeyboardKey = 0x%x\n", k.name, k.value)
	}
	b.WriteString(")\n\n")

	b.WriteString("// logicalKeyList lists the logical keys in the order of their ids.\nvar logicalKeyList = []LogicalKeyboardKey{\n")
	for _, k := range logical {
		fmt.Fprintf(&b, "\tLogicalKeyboardKey%s,\n", k.name)
	}
	b.WriteString("}\n\n")

	b.WriteString("// logicalKeyLabels are the labels of the logical keys.\nvar logicalKeyLabels = map[LogicalKeyboardKey]string{\n")
	for _, k := range logical {
		fmt.Fprintf(&b, "\tLogicalKeyboardKey%s: %q,\n", k.name, k.label)
	}
	b.WriteString("}\n\n")

	// Synonyms: the pseudo-key of each key, and the keys of each pseudo-key.
	pseudo := sortedKeys(d.synonyms)
	b.WriteString("// logicalKeySynonyms maps a key to the pseudo-key that stands for it.\nvar logicalKeySynonyms = map[LogicalKeyboardKey]LogicalKeyboardKey{\n")
	for _, p := range pseudo {
		for _, member := range d.synonyms[p] {
			if _, ok := d.logical[member]; !ok {
				return nil, errors.New(tagKeysSynonymUnknown, "a synonym names an unknown key", "key", member)
			}
			fmt.Fprintf(&b, "\tLogicalKeyboardKey%s: LogicalKeyboardKey%s,\n", member, p)
		}
	}
	b.WriteString("}\n\n")
	b.WriteString("// logicalKeyReverseSynonyms maps a pseudo-key to the keys it stands for.\nvar logicalKeyReverseSynonyms = map[LogicalKeyboardKey][]LogicalKeyboardKey{\n")
	for _, p := range pseudo {
		if _, ok := d.logical[p]; !ok {
			return nil, errors.New(tagKeysSynonymUnknown, "a synonym names an unknown key", "key", p)
		}
		fmt.Fprintf(&b, "\tLogicalKeyboardKey%s: {", p)
		for i, member := range d.synonyms[p] {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "LogicalKeyboardKey%s", member)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")

	b.WriteString("// The physical keys, in the order of their USB usages.\nconst (\n")
	for _, k := range physical {
		fmt.Fprintf(&b, "\t// PhysicalKeyboardKey%s is the location of the %q key on a generalized keyboard.\n\t//\n", k.name, k.label)
		fmt.Fprintf(&b, "\t// Flutter: services/keyboard_key.g.dart PhysicalKeyboardKey.%s\n", dartName(k.name))
		fmt.Fprintf(&b, "\tPhysicalKeyboardKey%s PhysicalKeyboardKey = 0x%08x\n", k.name, k.usb)
	}
	b.WriteString(")\n\n")
	b.WriteString("// physicalKeyList lists the physical keys in the order of their usages.\nvar physicalKeyList = []PhysicalKeyboardKey{\n")
	for _, k := range physical {
		fmt.Fprintf(&b, "\tPhysicalKeyboardKey%s,\n", k.name)
	}
	b.WriteString("}\n\n")
	// The physical key that has the name of a logical key: the place of A on a
	// QWERTY keyboard is the physical key of the logical key A.
	b.WriteString("// logicalToPhysicalKey maps a logical key to the physical key of the same name.\nvar logicalToPhysicalKey = map[LogicalKeyboardKey]PhysicalKeyboardKey{\n")
	physicalNames := map[string]bool{}
	for _, k := range physical {
		physicalNames[k.name] = true
	}
	for _, k := range logical {
		if physicalNames[k.name] {
			fmt.Fprintf(&b, "\tLogicalKeyboardKey%s: PhysicalKeyboardKey%s,\n", k.name, k.name)
		}
	}
	b.WriteString("}\n\n")
	b.WriteString("// physicalKeyNames are the debug names of the physical keys.\nvar physicalKeyNames = map[PhysicalKeyboardKey]string{\n")
	for _, k := range physical {
		fmt.Fprintf(&b, "\tPhysicalKeyboardKey%s: %q,\n", k.name, k.label)
	}
	b.WriteString("}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, errors.NewErr(tagKeysFormatFailed, err)
	}
	return out, nil
}

// The tags of the errors that this file makes (rm4n0s/errors, R5).
const (
	tagKeysSynonymUnknown = "KeysSynonymUnknown"
)
