package keys

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"

	"github.com/rm4n0s/errors"
)

// androidPressingGoal names the keys whose pressing state follows one bit of
// KeyEvent.getMetaState (KeyboardMap.pressingGoals): the Go name of the mask constant,
// and the physical and logical key names of the left and right keys.
type androidPressingGoal struct {
	mask string
	keys [2]string
}

// androidPressingGoals are Flutter's pressing goals, in Flutter's order.
var androidPressingGoals = []androidPressingGoal{
	{"metaCtrlOn", [2]string{"ControlLeft", "ControlRight"}},
	{"metaShiftOn", [2]string{"ShiftLeft", "ShiftRight"}},
	{"metaAltOn", [2]string{"AltLeft", "AltRight"}},
}

// androidTogglingGoals are Flutter's toggling goals (KeyboardMap.getTogglingGoals).
var androidTogglingGoals = []struct{ mask, key string }{
	{"metaCapsLockOn", "CapsLock"},
}

// androidScanCodes returns the Android scan codes (the "android" column of the physical
// key data, a list) of the key called name, and false when the key has none.
func (k physicalKey) androidScanCodes(name string) ([]uint64, bool, error) {
	raw, ok := k.ScanCodes["android"]
	if !ok {
		return nil, false, nil
	}
	var codes []uint64
	if err := json.Unmarshal(raw, &codes); err != nil {
		return nil, false, errors.NewErr(tagKeysDataInvalid, err).SetMetadata("key", name, "column", "android")
	}
	return codes, true, nil
}

// generateAndroid writes the tables of the Android platform: the physical key of each
// Android scan code, the logical key of each Android key code, and the pressing and
// toggling goals. It ports android_keyboard_map_java.tmpl of dev/tools/gen_keycodes, whose
// output is KeyboardMap.java.
func generateAndroid(d *data) ([]byte, error) {
	// Android scan code -> physical key (the USB HID usage Flutter uses as the id).
	scan := map[uint64]uint64{}
	scanOwner := map[uint64]string{}
	for _, name := range sortedKeys(d.physical) {
		k := d.physical[name]
		codes, ok, err := k.androidScanCodes(name)
		if err != nil {
			return nil, err
		}
		if !ok {
			continue
		}
		usb, hasUSB, err := k.scanCode(name, "usb")
		if err != nil {
			return nil, err
		}
		if !hasUSB {
			continue
		}
		for _, code := range codes {
			if prev, dup := scanOwner[code]; dup {
				return nil, errors.New(tagKeysDuplicate, "two physical keys share an Android scan code",
					"scanCode", code, "keys", []string{prev, name})
			}
			scanOwner[code] = name
			scan[code] = usb
		}
	}

	// Android key code -> logical key.
	code := map[uint64]uint64{}
	codeOwner := map[uint64]string{}
	for _, name := range sortedKeys(d.logical) {
		k := d.logical[name]
		for _, kc := range k.Values["android"] {
			if prev, dup := codeOwner[kc]; dup {
				return nil, errors.New(tagKeysDuplicate, "two logical keys share an Android key code",
					"keyCode", kc, "keys", []string{prev, name})
			}
			codeOwner[kc] = name
			code[kc] = k.Value
		}
	}

	// The goals: each key needs a physical and a logical key.
	var goalNames []string
	for _, g := range androidPressingGoals {
		goalNames = append(goalNames, g.keys[:]...)
	}
	for _, g := range androidTogglingGoals {
		goalNames = append(goalNames, g.key)
	}
	type pair struct{ physical, logical uint64 }
	pairs := map[string]pair{}
	for _, name := range goalNames {
		p, ok := d.physical[name]
		if !ok {
			return nil, errors.New(tagKeysGoalUnknown, "an Android goal names a key that has no physical key", "key", name)
		}
		usb, hasUSB, err := p.scanCode(name, "usb")
		if err != nil {
			return nil, err
		}
		if !hasUSB {
			return nil, errors.New(tagKeysGoalUnknown, "an Android goal names a physical key with no USB code", "key", name)
		}
		l, ok := d.logical[name]
		if !ok {
			return nil, errors.New(tagKeysGoalUnknown, "an Android goal names a key that has no logical key", "key", name)
		}
		pairs[name] = pair{usb, l.Value}
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by glutter-gen keys; DO NOT EDIT.\n")
	b.WriteString("// Source: Flutter's dev/tools/gen_keycodes/data (physical_key_data.g.json,\n")
	b.WriteString("// logical_key_data.g.json), the content of android_keyboard_map_java.tmpl.\n")
	b.WriteString("// Flutter is BSD-3-Clause licensed; see third_party/flutter/LICENSE.\n\n")
	b.WriteString("package android\n\n")

	b.WriteString("// The masks of a key id: the low 32 bits are the value, and the bits above them the plane.\n")
	b.WriteString("//\n// Flutter: engine/src/flutter/shell/platform/android/io/flutter/embedding/android/KeyboardMap.java KeyboardMap.kValueMask\n")
	b.WriteString("const (\n")
	b.WriteString("\tkeyValueMask    uint64 = 0x000ffffffff\n")
	b.WriteString("\tkeyUnicodePlane uint64 = 0x00000000000\n")
	b.WriteString("\tkeyAndroidPlane uint64 = 0x01100000000\n")
	b.WriteString(")\n\n")

	b.WriteString("// scanCodeToPhysical maps an Android scan code (KeyEvent.getScanCode) to the id of\n// Flutter's PhysicalKeyboardKey (the USB HID usage).\n//\n")
	b.WriteString("// Flutter: engine/src/flutter/shell/platform/android/io/flutter/embedding/android/KeyboardMap.java KeyboardMap.scanCodeToPhysical\n")
	b.WriteString("var scanCodeToPhysical = map[uint32]uint64{\n")
	for _, c := range sortedUint64(scan) {
		fmt.Fprintf(&b, "\t%d: 0x%x, // %s\n", c, scan[c], scanOwner[c])
	}
	b.WriteString("}\n\n")

	b.WriteString("// keyCodeToLogical maps an Android key code (KeyEvent.getKeyCode) to the id of\n// Flutter's LogicalKeyboardKey.\n//\n")
	b.WriteString("// Flutter: engine/src/flutter/shell/platform/android/io/flutter/embedding/android/KeyboardMap.java KeyboardMap.keyCodeToLogical\n")
	b.WriteString("var keyCodeToLogical = map[uint32]uint64{\n")
	for _, c := range sortedUint64(code) {
		fmt.Fprintf(&b, "\t%d: 0x%x, // %s\n", c, code[c], codeOwner[c])
	}
	b.WriteString("}\n\n")

	b.WriteString("// pressingGoals are the modifiers whose pressing state follows KeyEvent.getMetaState.\n//\n")
	b.WriteString("// Flutter: engine/src/flutter/shell/platform/android/io/flutter/embedding/android/KeyboardMap.java KeyboardMap.pressingGoals\n")
	b.WriteString("var pressingGoals = []pressingGoal{\n")
	for _, g := range androidPressingGoals {
		fmt.Fprintf(&b, "\t{mask: %s, keys: []keyPair{\n", g.mask)
		for _, name := range g.keys {
			fmt.Fprintf(&b, "\t\t{physical: 0x%x, logical: 0x%x}, // %s\n", pairs[name].physical, pairs[name].logical, name)
		}
		b.WriteString("\t}},\n")
	}
	b.WriteString("}\n\n")

	b.WriteString("// togglingGoals are the lock keys whose state follows KeyEvent.getMetaState.\n//\n")
	b.WriteString("// Flutter: engine/src/flutter/shell/platform/android/io/flutter/embedding/android/KeyboardMap.java KeyboardMap.getTogglingGoals\n")
	b.WriteString("var togglingGoals = []togglingGoal{\n")
	for _, g := range androidTogglingGoals {
		fmt.Fprintf(&b, "\t{mask: %s, physical: 0x%x, logical: 0x%x}, // %s\n", g.mask, pairs[g.key].physical, pairs[g.key].logical, g.key)
	}
	b.WriteString("}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, errors.NewErr(tagKeysFormatFailed, err)
	}
	return out, nil
}
