func macosFiles() map[string]string {
	f := validFiles()
	f["physical_key_data.g.json"] = `{
  "KeyA":      {"scanCodes": {"usb": 458756, "macos": 0}},
  "Space":     {"scanCodes": {"usb": 458796, "macos": 49}},
  "Enter":     {"scanCodes": {"usb": 458792, "macos": 36}},
  "NoMac":     {"scanCodes": {"usb": 900}},
  "NoUSB":     {"scanCodes": {"macos": 900}}
}`
	f["logical_key_data.g.json"] = `{
  "KeyA":  {"value": 97},
  "Space": {"value": 32},
  "Enter": {"value": 4294967309, "names": {"macos": ["Enter"]}, "values": {"macos": [36]}}
}`
	f["layout_goals.json"] = `{"KeyA": true, "Space": false}`
	return f
}

func writeFlutter(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	ref := filepath.Join(root, "flutter")
	dir := filepath.Join(ref, dataDir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.WriteFile(filepath.Join(root, "VERSION"), []byte("flutter_commit=abc123\nflutter_version=3.0.1\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	return ref
}

func TestRunGeneratesTheMacOSTables(t *testing.T) {
	ref := writeFlutter(t, macosFiles())
	out := filepath.Join(t.TempDir(), "keymap_gen.go")
	if err := Run([]string{"-reference", ref, "-out", "", "-macos-out", out}); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	text := squeeze(string(got))
	for _, want := range []string{
		"// Code generated by glutter-gen keys; DO NOT EDIT.",
		"commit abc123 (Flutter 3.0.1)",
		"package macos",
		"var keyCodeToPhysicalKey = map[uint16]uint64{",
		"0x0: 0x70004, // KeyA",
		"0x24: 0x70028, // Enter",
		"0x31: 0x7002c, // Space",
		"var keyCodeToLogicalKey = map[uint16]uint64{",
		"0x24: 0x10000000d, // Enter",
		"var layoutGoals = []layoutGoal{",
		"{keyCode: 0x31, logical: 0x20, mandatory: false}, // Space",
		"{keyCode: 0x0, logical: 0x61, mandatory: true}, // KeyA",
	} {
		if !strings.Contains(text, squeeze(want)) {
			t.Errorf("the macOS tables lack %q:\n%s", want, got)
		}
	}
	if strings.Contains(text, "NoMac") || strings.Contains(text, "NoUSB") {
		t.Error("a key with no macOS key code or no USB usage is in the tables")
	}
	// The goals are in the order of their Unicode values: Space (0x20) before KeyA (0x61).
	if strings.Index(text, "// Space") > strings.Index(text, "// KeyA") && strings.Contains(text, "layoutGoals") &&
		strings.LastIndex(text, "// Space") > strings.LastIndex(text, "// KeyA") {
		t.Error("the goals are not in the order of their logical keys")
	}
}

func TestMacOSErrors(t *testing.T) {
	tests := []struct {
		name    string
		mutate  func(f map[string]string)
		wantTag string
		route   string
	}{
		{"two physical keys share a key code", func(f map[string]string) {
			f["physical_key_data.g.json"] = `{"A": {"scanCodes": {"usb": 1, "macos": 5}}, "B": {"scanCodes": {"usb": 2, "macos": 5}}}`
		}, tagKeysDuplicate, "generateMacOS.KeysDuplicate"},
		{"two logical keys share a key code", func(f map[string]string) {
			f["logical_key_data.g.json"] = `{"A": {"value": 1, "values": {"macos": [5]}}, "B": {"value": 2, "values": {"macos": [5]}}}`
		}, tagKeysDuplicate, "generateMacOS.KeysDuplicate"},
		{"a goal with no key code", func(f map[string]string) {
			f["layout_goals.json"] = `{"Nowhere": true}`
		}, tagKeysGoalUnknown, "generateMacOS.KeysGoalUnknown"},
		{"a goal with no logical key", func(f map[string]string) {
			f["layout_goals.json"] = `{"Enter": true}`
			f["logical_key_data.g.json"] = `{"KeyA": {"value": 97}}`
		}, tagKeysGoalUnknown, "generateMacOS.KeysGoalUnknown"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			files := macosFiles()
			tt.mutate(files)
			ref := writeFlutter(t, files)
			err := Run([]string{"-reference", ref, "-out", "", "-macos-out", filepath.Join(t.TempDir(), "x.go")})
			appErr, ok := errors.FromError(err)
			if !ok || appErr.Tag != tt.wantTag || !appErr.HasRoute(tt.route) {
				t.Fatalf("err = %v (route %v), want %s via %s", err, errRoute(err), tt.wantTag, tt.route)
			}
		})
	}
}

func errRoute(err error) string {
	if appErr, ok := errors.FromError(err); ok {
		return appErr.Route()
	}
	return ""
}

// TestMacOSTablesMatchFlutterOwnGeneratedFile compares the tables with the KeyCodeMap.g.mm that Flutter
// generated from the same data: every key code, physical key, logical key and goal must be there with the same
// values. It needs the reference checkout of scripts/fetch-reference.sh.
func TestMacOSTablesMatchFlutterOwnGeneratedFile(t *testing.T) {
	const ref = "../../../../reference/flutter"
	mmPath := filepath.Join(ref, "engine/src/flutter/shell/platform/darwin/macos/framework/Source/KeyCodeMap.g.mm")
	mm, err := os.ReadFile(mmPath)
	if err != nil {
		t.Skip("no reference checkout with the macOS embedder: run scripts/fetch-reference.sh")
	}
	src, err := loadData(filepath.Join(ref, dataDir), false, false, false)
	if err != nil {
		t.Skip("no key data in the reference checkout")
	}
	out, err := generateMacOS(src, "test")
	if err != nil {
		t.Fatal(err)
	}
	entry := regexp.MustCompile(`@0x([0-9a-f]+) : @0x([0-9a-f]+),`)
	section := func(text, start, end string) string {
		i := strings.Index(text, start)
		if i < 0 {
			t.Fatalf("no %q", start)
		}
		j := strings.Index(text[i:], end)
		return text[i : i+j]
	}
	parse := func(sec string) map[uint64]uint64 {
		m := map[uint64]uint64{}
		for _, e := range entry.FindAllStringSubmatch(sec, -1) {
			k, _ := strconv.ParseUint(e[1], 16, 64)
			v, _ := strconv.ParseUint(e[2], 16, 64)
			m[k] = v
		}
		return m
	}
	goTable := func(name string) map[uint64]uint64 {
		sec := section(string(out), "var "+name, "\n}\n")
		goEntry := regexp.MustCompile(`0x([0-9a-f]+): +0x([0-9a-f]+),`)
		m := map[uint64]uint64{}
		for _, e := range goEntry.FindAllStringSubmatch(sec, -1) {
			k, _ := strconv.ParseUint(e[1], 16, 64)
			v, _ := strconv.ParseUint(e[2], 16, 64)
			m[k] = v
		}
		return m
	}
	for _, tc := range []struct{ goName, mmName string }{
		{"keyCodeToPhysicalKey", "const NSDictionary* keyCodeToPhysicalKey"},
		{"keyCodeToLogicalKey", "const NSDictionary* keyCodeToLogicalKey"},
	} {
		want := parse(section(string(mm), tc.mmName, "\n};"))
		got := goTable(tc.goName)
		if len(want) == 0 || len(got) != len(want) {
			t.Errorf("%s has %d entries, Flutter's has %d", tc.goName, len(got), len(want))
		}
		for k, v := range want {
			if got[k] != v {
				t.Errorf("%s[0x%x] = 0x%x, Flutter's is 0x%x", tc.goName, k, got[k], v)
			}
		}
	}
	// The goals.
	goalRe := regexp.MustCompile(`LayoutGoal\{0x([0-9a-f]+), 0x([0-9a-f]+), (true|false)\}`)
	want := goalRe.FindAllStringSubmatch(section(string(mm), "const std::vector<LayoutGoal> kLayoutGoals", "\n};"), -1)
	gotGoals := regexp.MustCompile(`keyCode: 0x([0-9a-f]+), logical: 0x([0-9a-f]+), mandatory: (true|false)`).FindAllStringSubmatch(string(out), -1)
	if len(want) == 0 || len(gotGoals) != len(want) {
		t.Fatalf("%d goals, Flutter has %d", len(gotGoals), len(want))
	}
	for i := range want {
		hex := func(s string) uint64 { v, _ := strconv.ParseUint(s, 16, 64); return v }
		if hex(want[i][1]) != hex(gotGoals[i][1]) || hex(want[i][2]) != hex(gotGoals[i][2]) || want[i][3] != gotGoals[i][3] {
			t.Errorf("goal %d is %v, Flutter's is %v", i, gotGoals[i][1:], want[i][1:])
		}
	}
}
