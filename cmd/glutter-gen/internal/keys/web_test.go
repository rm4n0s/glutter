func webFiles() map[string]string {
	f := validFiles()
	f["physical_key_data.g.json"] = `{
  "KeyA":   {"names": {"name": "KeyA", "chromium": "KeyA"}, "scanCodes": {"usb": 458756, "xkb": 38}},
  "Escape": {"names": {"name": "Escape", "chromium": "Escape"}, "otherWebCodes": ["Esc"], "scanCodes": {"usb": 458793}},
  "KeyB":   {"names": {"name": "KeyB", "chromium": "KeyB"}, "scanCodes": {"usb": 458757}},
  "Fn":     {"names": {"name": "Fn"}, "scanCodes": {"usb": 18}}
}`
	f["logical_key_data.g.json"] = `{
  "KeyA":      {"name": "KeyA", "value": 97},
  "KeyB":      {"name": "KeyB", "value": 98},
  "Enter":     {"name": "Enter", "value": 4294967309, "names": {"web": ["Enter"], "gtk": ["Return"]}},
  "Escape":    {"name": "Escape", "value": 4294967323, "names": {"web": ["Escape", "Esc"]}},
  "ShiftLeft": {"name": "ShiftLeft", "value": 8589934850},
  "ShiftRight": {"name": "ShiftRight", "value": 8589934851},
  "Shift":     {"name": "Shift", "value": 8589934850}
}`
	f["web_logical_location_mapping.json"] = `{"Shift": ["ShiftLeft", "ShiftLeft", "ShiftRight", null], "Enter": ["Enter", null, null, null]}`
	return f
}

func TestRunGeneratesTheWebTables(t *testing.T) {
	ref := writeData(t, webFiles())
	out := filepath.Join(t.TempDir(), "keymap_gen.go")
	if err := Run([]string{"-reference", ref, "-out", "", "-web-out", out}); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	text := squeeze(string(got))
	for _, want := range []string{
		"// Code generated by glutter-gen keys; DO NOT EDIT.",
		"package web",
		`"KeyA": 0x70004,`,
		`"Escape": 0x70029,`,
		`"Esc": 0x70029,`, // an older code of the same key
		`"Enter": 0x10000000d,`,
		`"Esc": 0x10000001b,`,
		`"Shift": {0x200000102, 0x200000102, 0x200000103, 0x0},`,
		`"Enter": {0x10000000d, 0x0, 0x0, 0x0},`,
		`"KeyA": {logical: 0x61, mandatory: true},`,
		`"KeyB": {logical: 0x62, mandatory: false},`,
	} {
		if !strings.Contains(text, squeeze(want)) {
			t.Errorf("the output lacks %q:\n%s", want, got)
		}
	}
	// A physical key without a web code (Fn) is not there.
	if strings.Contains(text, "Fn") {
		t.Errorf("the output has a key without a web code:\n%s", got)
	}
	// The file is only written when it changes.
	info1, err := os.Stat(out)
	if err != nil {
		t.Fatal(err)
	}
	if err := Run([]string{"-reference", ref, "-out", "", "-web-out", out}); err != nil {
		t.Fatal(err)
	}
	again, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	info2, err := os.Stat(out)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, again) || !info2.ModTime().Equal(info1.ModTime()) {
		t.Error("the second run changed the file")
	}
}

func TestWebFailures(t *testing.T) {
	with := func(name, content string) map[string]string {
		f := webFiles()
		f[name] = content
		return f
	}
	tests := []struct {
		name  string
		files map[string]string
		tag   string
		route string
	}{
		{"the location mapping is missing", func() map[string]string { f := webFiles(); delete(f, "web_logical_location_mapping.json"); return f }(), "KeysDataMissing", "Run->loadData.KeysDataMissing"},
		{"a location mapping with three entries", with("web_logical_location_mapping.json", `{"Shift": ["ShiftLeft", null, null]}`), "KeysDataInvalid", "generateWeb.KeysDataInvalid"},
		{"a location mapping with an unknown key", with("web_logical_location_mapping.json", `{"Shift": ["Nope", null, null, null]}`), "KeysGoalUnknown", "generateWeb.KeysGoalUnknown"},
		{"two physical keys with the same code", with("physical_key_data.g.json", `{"KeyA": {"names": {"chromium": "KeyA"}, "scanCodes": {"usb": 1}}, "KeyB": {"names": {"chromium": "KeyA"}, "scanCodes": {"usb": 2}}}`), "KeysDuplicate", "generateWeb.KeysDuplicate"},
		{"two logical keys with the same web name", with("logical_key_data.g.json", `{"KeyA": {"value": 97, "names": {"web": ["X"]}}, "KeyB": {"value": 98, "names": {"web": ["X"]}}}`), "KeysDuplicate", "generateWeb.KeysDuplicate"},
		{"a goal whose key has no web code", with("layout_goals.json", `{"Fn": true}`), "KeysGoalUnknown", "generateWeb.KeysGoalUnknown"},
		{"a goal without a logical key", with("logical_key_data.g.json", `{"KeyB": {"value": 98}}`), "KeysGoalUnknown", "generateWeb.KeysGoalUnknown"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			ref := writeData(t, tt.files)
			err := Run([]string{"-reference", ref, "-out", "", "-web-out", filepath.Join(t.TempDir(), "out.go")})
			appErr, ok := errors.FromError(err)
			if !ok {
				t.Fatalf("expected *errors.Error, got %T (%v)", err, err)
			}
			if appErr.Tag != tt.tag || !appErr.HasRoute(tt.route) {
				t.Errorf("got %s via %s, want %s via %s", appErr.Tag, appErr.Route(), tt.tag, tt.route)
			}
		})
	}
}

// TestCommittedWebTablesAreCurrent regenerates the web tables from Flutter's data and compares them with
// the committed file (skipped where reference/ is missing).
func TestCommittedWebTablesAreCurrent(t *testing.T) {
	ref := filepath.Join("..", "..", "..", "..", "reference", "flutter")
	if _, err := os.Stat(filepath.Join(ref, dataDir)); err != nil {
		t.Skipf("reference/ is missing, so the tables cannot be regenerated: run scripts/fetch-reference.sh (%v)", err)
	}
	out := filepath.Join(t.TempDir(), "keymap_gen.go")
	if err := Run([]string{"-reference", ref, "-out", "", "-web-out", out}); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	committed, err := os.ReadFile(filepath.Join("..", "..", "..", "..", "internal", "platform", "web", "keymap_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, committed) {
		t.Error("internal/platform/web/keymap_gen.go is stale: run go generate ./internal/platform/web/")
	}
}
