package keys

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"

	"github.com/rm4n0s/errors"
)

// generateWeb writes the tables of the web platform: the physical key of each
// KeyboardEvent.code (the "chromium" names of the physical key data), the logical key
// of each non-printable KeyboardEvent.key (the "web" names of the logical key data), the
// logical keys of the keys that depend on KeyboardEvent.location, and the layout goals by
// code. It ports the web tables of dev/tools/gen_keycodes (web_key_map_dart.tmpl).
func generateWeb(d *data) ([]byte, error) {
	// KeyboardEvent.code -> physical key (the USB HID usage Flutter uses as the id).
	physical := map[string]uint64{}
	for _, name := range sortedKeys(d.physical) {
		k := d.physical[name]
		code, ok := k.Names["chromium"]
		if !ok {
			continue
		}
		usb, hasUSB, err := k.scanCode(name, "usb")
		if err != nil {
			return nil, err
		}
		if !hasUSB {
			continue
		}
		for _, c := range append([]string{code}, k.OtherWebCodes...) {
			if prev, dup := physical[c]; dup && prev != usb {
				return nil, errors.New(tagKeysDuplicate, "two physical keys share a KeyboardEvent.code", "code", c)
			}
			physical[c] = usb
		}
	}

	// KeyboardEvent.key -> logical key.
	logical := map[string]uint64{}
	for _, name := range sortedKeys(d.logical) {
		k := d.logical[name]
		for _, web := range k.Names["web"] {
			if prev, dup := logical[web]; dup && prev != k.Value {
				return nil, errors.New(tagKeysDuplicate, "two logical keys share a KeyboardEvent.key", "key", web)
			}
			logical[web] = k.Value
		}
	}

	// KeyboardEvent.key -> the logical keys at the four locations.
	locations := map[string][4]uint64{}
	for _, key := range sortedKeys(d.webLocations) {
		names := d.webLocations[key]
		if len(names) != 4 {
			return nil, errors.New(tagKeysDataInvalid, "a web location mapping needs four entries", "key", key)
		}
		var ids [4]uint64
		for i, n := range names {
			if n == nil {
				continue
			}
			l, ok := d.logical[*n]
			if !ok {
				return nil, errors.New(tagKeysGoalUnknown, "a web location mapping names a key that has no logical key", "key", key, "name", *n)
			}
			ids[i] = l.Value
		}
		locations[key] = ids
	}

	// KeyboardEvent.code -> layout goal.
	goals := map[string]goal{}
	for _, name := range sortedKeys(d.goals) {
		p, ok := d.physical[name]
		code := p.Names["chromium"]
		if !ok || code == "" {
			return nil, errors.New(tagKeysGoalUnknown, "a layout goal names a physical key with no KeyboardEvent.code", "key", name)
		}
		l, ok := d.logical[name]
		if !ok {
			return nil, errors.New(tagKeysGoalUnknown, "a layout goal names a key that has no logical key", "key", name)
		}
		goals[code] = goal{name: name, logical: l.Value, mandatory: d.goals[name]}
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by glutter-gen keys; DO NOT EDIT.\n")
	b.WriteString("// Source: Flutter's dev/tools/gen_keycodes/data (physical_key_data.g.json,\n")
	b.WriteString("// logical_key_data.g.json, layout_goals.json, web_logical_location_mapping.json).\n")
	b.WriteString("// Flutter is BSD-3-Clause licensed; see third_party/flutter/LICENSE.\n\n")
	b.WriteString("package web\n\n")

	b.WriteString("// webCodeToPhysicalKey maps KeyboardEvent.code to the id of Flutter's\n// PhysicalKeyboardKey (the USB HID usage).\n")
	b.WriteString("var webCodeToPhysicalKey = map[string]uint64{\n")
	for _, code := range sortedKeys(physical) {
		fmt.Fprintf(&b, "\t%q: 0x%x,\n", code, physical[code])
	}
	b.WriteString("}\n\n")

	b.WriteString("// webKeyToLogicalKey maps KeyboardEvent.key to the id of Flutter's\n// LogicalKeyboardKey, for the keys that are not printable characters.\n")
	b.WriteString("var webKeyToLogicalKey = map[string]uint64{\n")
	for _, key := range sortedKeys(logical) {
		fmt.Fprintf(&b, "\t%q: 0x%x,\n", key, logical[key])
	}
	b.WriteString("}\n\n")

	b.WriteString("// webKeyLocationLogicalKey maps KeyboardEvent.key to the ids of the logical keys\n")
	b.WriteString("// that depend on KeyboardEvent.location: standard, left, right and numpad. A zero\n// id means the key has no logical key there.\n")
	b.WriteString("var webKeyLocationLogicalKey = map[string][4]uint64{\n")
	for _, key := range sortedKeys(locations) {
		ids := locations[key]
		fmt.Fprintf(&b, "\t%q: {0x%x, 0x%x, 0x%x, 0x%x},\n", key, ids[0], ids[1], ids[2], ids[3])
	}
	b.WriteString("}\n\n")

	b.WriteString("// webLayoutGoals lists the keys, by KeyboardEvent.code, whose logical key does not\n// follow the layout.\n")
	b.WriteString("var webLayoutGoals = map[string]webLayoutGoal{\n")
	codes := make([]string, 0, len(goals))
	for c := range goals {
		codes = append(codes, c)
	}
	sort.Strings(codes)
	for _, c := range codes {
		g := goals[c]
		fmt.Fprintf(&b, "\t%q: {logical: 0x%x, mandatory: %t},\n", c, g.logical, g.mandatory)
	}
	b.WriteString("}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, errors.NewErr(tagKeysFormatFailed, err)
	}
	return out, nil
}
