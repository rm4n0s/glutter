func writeFiles(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

const sample = `package sample

import (
	"github.com/rm4n0s/glutter/foundation"
	"github.com/rm4n0s/glutter/ui"
	p "github.com/rm4n0s/glutter/painting"
)

// Scheme is a set of colors.
//
//glutter:copywith
//
// Flutter: material/color_scheme.dart ColorScheme
type Scheme struct {
	Primary ui.Color
	size    float64
	style   *p.TextStyle
	extra   foundation.Opt[int]
	skipped int ` + "`copywith:\"-\"`" + `
	Names   []string
}

// Point is a value.
//
//glutter:copywith value
type Point struct{ X, Y float64 }

// Plain has no marker.
type Plain struct{ A int }
`

const wantSample = `// Code generated by glutter-gen copywith; DO NOT EDIT.

package sample

import (
	foundation "github.com/rm4n0s/glutter/foundation"
	p "github.com/rm4n0s/glutter/painting"
	ui "github.com/rm4n0s/glutter/ui"
)

// PointCopy holds the replacements for Point.CopyWith: a field that is None keeps the value of the
// copied one.
//
// Flutter: no counterpart
type PointCopy struct {
	X foundation.Opt[float64]
	Y foundation.Opt[float64]
}

// CopyWith returns a copy of the Point with the fields that the PointCopy sets replaced.
//
// Flutter: no counterpart
func (x Point) CopyWith(c PointCopy) Point {
	r := x
	if v, ok := c.X.Get(); ok {
		r.X = v
	}
	if v, ok := c.Y.Get(); ok {
		r.Y = v
	}
	return r
}

// SchemeCopy holds the replacements for Scheme.CopyWith: a field that is None keeps the value of the
// copied one.
//
// Flutter: material/color_scheme.dart ColorScheme.copyWith
type SchemeCopy struct {
	Primary foundation.Opt[ui.Color]
	Size    foundation.Opt[float64]
	Style   foundation.Opt[*p.TextStyle]
	Extra   foundation.Opt[int]
	Names   foundation.Opt[[]string]
}

// CopyWith returns a copy of the Scheme with the fields that the SchemeCopy sets replaced.
//
// Flutter: material/color_scheme.dart ColorScheme.copyWith
func (x *Scheme) CopyWith(c SchemeCopy) *Scheme {
	r := *x
	if v, ok := c.Primary.Get(); ok {
		r.Primary = v
	}
	if v, ok := c.Size.Get(); ok {
		r.size = v
	}
	if v, ok := c.Style.Get(); ok {
		r.style = v
	}
	if c.Extra.IsSome() {
		r.extra = c.Extra
	}
	if v, ok := c.Names.Get(); ok {
		r.Names = v
	}
	return &r
}
`

func TestGenerate(t *testing.T) {
	dir := writeFiles(t, map[string]string{"scheme.go": sample, "scheme_test.go": "package sample\nthis is not Go", "copywith_gen.go": "package sample\nnot parsed"})
	got, err := Generate(dir, "copywith_gen.go")
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != wantSample {
		t.Errorf("generated:\n%s\nwant:\n%s", got, wantSample)
	}
}

func TestRunWritesTheFileOnlyWhenItChanged(t *testing.T) {
	dir := writeFiles(t, map[string]string{"scheme.go": sample})
	if err := Run([]string{"-dir", dir}); err != nil {
		t.Fatal(err)
	}
	out := filepath.Join(dir, defaultOut)
	first, err := os.Stat(out)
	if err != nil {
		t.Fatal(err)
	}
	data, _ := os.ReadFile(out)
	if string(data) != wantSample {
		t.Errorf("file = %s", data)
	}
	if err := Run([]string{"-dir", dir}); err != nil { // the second run reads the file it wrote, and skips it
		t.Fatal(err)
	}
	second, _ := os.Stat(out)
	if !second.ModTime().Equal(first.ModTime()) {
		t.Error("the file was written again")
	}
}

func TestFieldsThatAreOptKeepTheirType(t *testing.T) {
	dir := writeFiles(t, map[string]string{"a.go": `package a

import "github.com/rm4n0s/glutter/foundation"

//glutter:copywith
type A struct {
	Width foundation.Opt[float64]
	Height float64
}
`})
	got, err := Generate(dir, "")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(got), "Width  foundation.Opt[float64]\n") || strings.Contains(string(got), "Opt[foundation.Opt") {
		t.Errorf("generated:\n%s", got)
	}
	// A field that is an Opt is replaced as it is when the replacement is set; the
	// others are replaced by the value in the Opt.
	if !strings.Contains(string(got), "if c.Width.IsSome() {\n\t\tr.Width = c.Width\n") || !strings.Contains(string(got), "if v, ok := c.Height.Get(); ok {") {
		t.Errorf("replacement of the fields:\n%s", got)
	}
}

func TestInsideFoundationNeedsNoImport(t *testing.T) {
	dir := writeFiles(t, map[string]string{"a.go": `package foundation

//glutter:copywith
type A struct{ N int }
`})
	got, err := Generate(dir, "")
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(got), "glutter/foundation") || !strings.Contains(string(got), "N Opt[int]") {
		t.Errorf("generated:\n%s", got)
	}
}

func TestFailuresHaveTheirOwnRoutes(t *testing.T) {
	tests := []struct {
		name  string
		files map[string]string
		args  func(dir string) []string
		route string
	}{
		{"bad flags", nil, func(string) []string { return []string{"-nope"} }, "Run.CopyWithBadFlags"},
		{"no directory", nil, func(string) []string { return []string{"-dir", "/no/such/dir"} }, "Run.Generate.CopyWithReadDirFailed"},
		{"parse", map[string]string{"a.go": "package a\nnot go"}, nil, "Run.Generate.CopyWithParseFailed"},
		{"two packages", map[string]string{"a.go": "package a", "b.go": "package b"}, nil, "Run.Generate.CopyWithPackagesMixed"},
		{"no types", map[string]string{"a.go": "package a\ntype A struct{ N int }"}, nil, "Run.Generate.CopyWithNoTypes"},
		{"not a struct", map[string]string{"a.go": "package a\n//glutter:copywith\ntype A int"}, nil, "Run.Generate.targetsOf.CopyWithNotAStruct"},
		{"generic", map[string]string{"a.go": "package a\n//glutter:copywith\ntype A[T any] struct{ N T }"}, nil, "Run.Generate.targetsOf.CopyWithGeneric"},
		{"no fields", map[string]string{"a.go": "package a\n//glutter:copywith\ntype A struct{ _ int }"}, nil, "Run.Generate.targetsOf.CopyWithNoFields"},
		{"name clash", map[string]string{"a.go": "package a\n//glutter:copywith\ntype A struct{ n, N int }"}, nil, "Run.Generate.targetsOf.CopyWithNameClash"},
		{"unknown import", map[string]string{"a.go": "package a\n//glutter:copywith\ntype A struct{ N ui.Color }"}, nil, "Run.Generate.CopyWithUnknownImport"},
		{"write", map[string]string{"a.go": "package a\n//glutter:copywith\ntype A struct{ N int }"}, func(dir string) []string {
			return []string{"-dir", dir, "-out", filepath.Join(dir, "no", "such", "out.go")}
		}, "Run.CopyWithWriteFailed"},
		{"import clash", map[string]string{
			"a.go": "package a\nimport x \"p/one\"\n//glutter:copywith\ntype A struct{ N x.T }",
			"b.go": "package a\nimport x \"p/two\"\n//glutter:copywith\ntype B struct{ N x.T }",
		}, nil, "Run.Generate.CopyWithImportClash"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := writeFiles(t, tt.files)
			args := []string{"-dir", dir}
			if tt.args != nil {
				args = tt.args(dir)
			}
			err := Run(args)
			appErr, ok := errors.FromError(err)
			if !ok {
				t.Fatalf("expected *errors.Error, got %T (%v)", err, err)
			}
			if !appErr.HasRoute(tt.route[strings.LastIndex(tt.route, ".")+1:]) {
				t.Errorf("unexpected failure path: %s, want ...%s", appErr.Route(), tt.route)
			}
		})
	}
}
