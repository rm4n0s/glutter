func TestParseMappings(t *testing.T) {
	got, err := parseMappings(mappingsSample)
	if err != nil {
		t.Fatal(err)
	}
	want := map[string][]string{
		"XInput":  {"xinput,*,a:b0,b:b1,"},
		"WGI":     {"03000000491900001904000000007700,Amazon Luna Controller,a:b0,b:b1,", `030000007e0500000920000000007701,Nintendo "Pro" Controller,a:b0,`},
		"DInput":  {"03000000d11800000094000000007700,DInput Pad,a:b0,"},
		"Linux":   {"03000000d11800000094000000010000,Linux Pad,a:b0,"},
		"Android": {"05000000d11800000094000000010000,Android Pad,a:b0,"},
		"Web":     {"default,*,a:b0,"},
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("parseMappings() =\n%v\nwant\n%v", got, want)
	}
}

func TestParseMappingsFails(t *testing.T) {
	tests := []struct {
		name, src string
	}{
		{"an #endif without an #if", "#endif\n"},
		{"a missing section", "#ifdef SDL_JOYSTICK_XINPUT\n \"x,*,a:b0,\",\n#endif\n"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			_, err := parseMappings(tt.src)
			appErr, ok := errors.FromError(err)
			if !ok {
				t.Fatalf("expected *errors.Error, got %T (%v)", err, err)
			}
			if !appErr.HasRoute("parseMappings.GamepadDBSyntax") {
				t.Errorf("unexpected failure path: %s", appErr.Route())
			}
		})
	}
}

func controllerLines(n int) string {
	var b strings.Builder
	for i := 0; i < n; i++ {
		b.WriteString("    { MAKE_CONTROLLER_ID( 0x045e, 0x")
		b.WriteString(strings.Repeat("0", 4-len(hex(i))) + hex(i))
		b.WriteString(" ), k_eControllerType_XBox360Controller, NULL },\n")
	}
	return b.String()
}

func hex(n int) string {
	const d = "0123456789abcdef"
	if n == 0 {
		return "0"
	}
	s := ""
	for ; n > 0; n /= 16 {
		s = string(d[n%16]) + s
	}
	return s
}

func TestParseControllers(t *testing.T) {
	src := controllerLines(120) +
		"    { MAKE_CONTROLLER_ID( 0x054c, 0x0ce6 ), k_eControllerType_PS5Controller, \"DualSense Wireless Controller\" }, // PS5\n" +
		"    // { MAKE_CONTROLLER_ID( 0x1111, 0x2222 ), k_eControllerType_PS3Controller, NULL },\n" +
		"    { MAKE_CONTROLLER_ID( 0x057e, 0x2009 ), k_eControllerType_SwitchProController, NULL },\n"
	got, err := parseControllers(src)
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 122 {
		t.Fatalf("got %d controllers, want 122 (the commented one is left out)", len(got))
	}
	if c := got[120]; c.vendor != 0x054c || c.product != 0x0ce6 || c.typ != "PS5Controller" || c.name != "DualSense Wireless Controller" {
		t.Errorf("controller = %+v", c)
	}
	if c := got[121]; c.typ != "SwitchProController" || c.name != "" {
		t.Errorf("controller = %+v", c)
	}
	if _, err := parseControllers("// nothing\n"); err == nil {
		t.Error("a list with no entries was accepted")
	} else if appErr, _ := errors.FromError(err); appErr == nil || !appErr.HasRoute("parseControllers.GamepadDBSyntax") {
		t.Errorf("unexpected failure: %v", err)
	}
}

func TestGenerateControllersKeepsTheFirstOfADuplicateAndSorts(t *testing.T) {
	code, err := generateControllers([]controller{
		{0x057e, 0x2009, "SwitchProController", ""},
		{0x045e, 0x028e, "XBox360Controller", "Xbox 360 Controller"},
		{0x057e, 0x2009, "PS4Controller", "later"},
	})
	if err != nil {
		t.Fatal(err)
	}
	s := string(code)
	first := strings.Index(s, "{0x045e, 0x028e, ControllerXBox360Controller, \"Xbox 360 Controller\"}")
	second := strings.Index(s, "{0x057e, 0x2009, ControllerSwitchProController, \"\"}")
	if first < 0 || second < 0 || first > second {
		t.Errorf("the entries are wrong or not sorted:\n%s", s)
	}
	if strings.Contains(s, "later") || strings.Contains(s, "ControllerPS4Controller ") {
		t.Errorf("a duplicate was kept:\n%s", s)
	}
	if !strings.HasPrefix(s, "// Code generated by glutter-gen gamepaddb; DO NOT EDIT.") {
		t.Errorf("the notice is missing:\n%s", s[:80])
	}
}

func TestRunWritesTheFilesOnlyWhenTheyChange(t *testing.T) {
	ref := t.TempDir()
	dir := filepath.Join(ref, "src", "joystick")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "SDL_gamepad_db.h"), []byte(mappingsSample), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "controller_list.h"), []byte(controllerLines(150)), 0o644); err != nil {
		t.Fatal(err)
	}
	out := t.TempDir()
	if err := Run([]string{"-reference", ref, "-out", out}); err != nil {
		t.Fatal(err)
	}
	mappings := filepath.Join(out, "mappings_gen.go")
	info1, err := os.Stat(mappings)
	if err != nil {
		t.Fatal(err)
	}
	b, _ := os.ReadFile(mappings)
	if !strings.Contains(string(b), "var Linux = []string{") || !strings.Contains(string(b), `"03000000d11800000094000000010000,Linux Pad,a:b0,"`) {
		t.Errorf("mappings_gen.go is wrong:\n%s", b)
	}
	if err := os.Chtimes(mappings, info1.ModTime().Add(-3600e9), info1.ModTime().Add(-3600e9)); err != nil {
		t.Fatal(err)
	}
	old, _ := os.Stat(mappings)
	if err := Run([]string{"-reference", ref, "-out", out}); err != nil {
		t.Fatal(err)
	}
	again, _ := os.Stat(mappings)
	if !again.ModTime().Equal(old.ModTime()) {
		t.Error("an unchanged file was written again")
	}
}

func TestRunFailures(t *testing.T) {
	tests := []struct {
		name  string
		args  []string
		route string
	}{
		{"a flag that does not exist", []string{"-nope"}, "Run.GamepadDBBadFlags"},
		{"no reference", []string{"-reference", "/nonexistent-dir", "-out", t.TempDir()}, "Run.GamepadDBReadFailed"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			err := Run(tt.args)
			appErr, ok := errors.FromError(err)
			if !ok {
				t.Fatalf("expected *errors.Error, got %T (%v)", err, err)
			}
			if !appErr.HasRoute(tt.route) {
				t.Errorf("unexpected failure path: %s", appErr.Route())
			}
		})
	}
	// An output directory that does not exist cannot be written to.
	ref := t.TempDir()
	dir := filepath.Join(ref, "src", "joystick")
	_ = os.MkdirAll(dir, 0o755)
	_ = os.WriteFile(filepath.Join(dir, "SDL_gamepad_db.h"), []byte(mappingsSample), 0o644)
	_ = os.WriteFile(filepath.Join(dir, "controller_list.h"), []byte(controllerLines(150)), 0o644)
	err := Run([]string{"-reference", ref, "-out", filepath.Join(t.TempDir(), "missing")})
	appErr, ok := errors.FromError(err)
	if !ok || !appErr.HasRoute("Run->writeIfChanged.GamepadDBWriteFailed") {
		t.Errorf("unexpected failure: %v", err)
	}
}

