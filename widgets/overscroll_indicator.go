// stretchingOverscrollIndicatorState is the state of a
// StretchingOverscrollIndicator.
//
// Flutter: widgets/overscroll_indicator.dart _StretchingOverscrollIndicatorState
type stretchingOverscrollIndicatorState struct {
	StateOf[*StretchingOverscrollIndicator]
	TickerProvider

	stretchController          *stretchController
	lastOverscrollNotification *OverscrollNotification
	totalOverscroll            float64
	accepted                   bool
}

func (s *stretchingOverscrollIndicatorState) InitState() {
	s.accepted = true
	s.stretchController = newStretchController(s, WidgetsBindingOf(s.Context()).Post)
}

func (s *stretchingOverscrollIndicatorState) handleScrollNotification(notification ScrollNotification) bool {
	w := s.Widget()
	if !w.o.NotificationPredicate(notification) {
		return false
	}
	metrics := notification.Metrics()
	if metrics.Axis() != w.Axis() {
		// This widget is explicitly configured to one axis. If a notification
		// from a different axis bubbles up, do nothing.
		return false
	}
	switch n := notification.(type) {
	case *ScrollStartNotification:
		s.accepted = true
		s.totalOverscroll = 0.0
	case *OverscrollNotification:
		s.lastOverscrollNotification = n
		// Flutter: _lastNotification.runtimeType is a Type, which is never an
		// OverscrollNotification, so the check `is!` is always true at the
		// pinned commit and the confirmation is dispatched for every overscroll
		// notification.
		confirmationNotification := NewOverscrollIndicatorNotification(n.Overscroll < 0.0)
		DispatchNotification(s.Context(), confirmationNotification)
		s.accepted = confirmationNotification.accepted

		if s.accepted {
			s.totalOverscroll += n.Overscroll

			if n.Velocity != 0.0 {
				if foundation.DebugMode && n.DragDetails.IsSome() {
					panic(errors.New(tagStretchingOverscrollVelocityWithDrag, "an OverscrollNotification with a velocity must not have drag details",
						"velocity", n.Velocity))
				}
				s.stretchController.absorbImpact(n.Velocity)
			} else if n.DragDetails.IsSome() {
				// We clamp the overscroll amount relative to the length of the
				// viewport, which is the furthest distance a single pointer could
				// pull on the screen. This is because more than one pointer will
				// multiply the amount of overscroll -
				// https://github.com/flutter/flutter/issues/11884
				viewportDimension := metrics.ViewportDimension()
				distanceForPull := s.totalOverscroll / viewportDimension
				clampedOverscroll := ui.ClampDouble(distanceForPull, -1.0, 1.0)
				s.stretchController.pull(clampedOverscroll)
			}
		}
	case *ScrollEndNotification:
		var velocity float64
		if details, ok := n.DragDetails.Get(); ok {
			if w.Axis() == painting.AxisVertical {
				velocity = details.Velocity.PixelsPerSecond.Dy
			} else {
				velocity = details.Velocity.PixelsPerSecond.Dx
			}
		}

		// Reverse axis directions report dragDetails velocity in the opposite
		// screen coordinate, so the value must be inverted.
		if metrics.AxisDirection() == painting.AxisDirectionLeft || metrics.AxisDirection() == painting.AxisDirectionUp {
			velocity = -velocity
		}

		// Since the overscrolling ended, we reset the total overscroll amount.
		s.totalOverscroll = 0.0
		if s.accepted {
			s.stretchController.scrollEnd(velocity)
		}
	case *ScrollUpdateNotification:
		s.totalOverscroll = 0.0
		s.stretchController.scrollEnd(0.0)
	}
	return false
}

func (s *stretchingOverscrollIndicatorState) Dispose() { s.stretchController.dispose() }

func (s *stretchingOverscrollIndicatorState) Build(BuildContext) Widget {
	w := s.Widget()
	return NewNotificationListener(s.handleScrollNotification,
		NewAnimatedBuilder(s.stretchController, func(bc BuildContext, _ Widget) Widget {
			stretch := s.stretchController.overscroll()
			var mainAxisSize float64
			switch w.Axis() {
			case painting.AxisHorizontal:
				mainAxisSize = MediaQueryWidthOf(bc)
			case painting.AxisVertical:
				mainAxisSize = MediaQueryHeightOf(bc)
			}

			viewportDimension := mainAxisSize
			if s.lastOverscrollNotification != nil {
				viewportDimension = s.lastOverscrollNotification.Metrics().ViewportDimension()
			}

			overscroll := -stretch

			// Adjust overscroll for reverse scroll directions.
			if w.axisDirection == painting.AxisDirectionUp || w.axisDirection == painting.AxisDirectionLeft {
				overscroll = -overscroll
			}

			var child Widget = NewSizedBoxShrink(nil)
			if w.child != nil {
				child = w.child
			}
			transform := NewStretchEffect(w.Axis(), child, StretchEffectOpts{StretchStrength: overscroll})

			// Only clip if the viewport dimension is smaller than that of the
			// screen size in the main axis. If the viewport takes up the whole
			// screen, overflow from transforming the viewport is irrelevant.
			clipBehavior := ui.ClipNone
			if stretch != 0.0 && viewportDimension != mainAxisSize {
				clipBehavior = w.o.ClipBehavior
			}
			return NewClipRect(transform, ClipRectOpts{ClipBehavior: clipBehavior})
		}, nil))
}

// stretchController animates the stretch of a scrollable.
//
// Flutter: widgets/overscroll_indicator.dart _StretchController
type stretchController struct {
	vsync scheduler.TickerProvider
	// post runs a function on the UI thread, after the work that is running now:
	// the microtask in which Dart runs the whenComplete callback of a future.
	post       func(func())
	controller *animation.AnimationController

	// overscrollNotifier manages and notifies changes to the current overscroll
	// value.
	overscrollNotifier *foundation.ValueNotifier[float64]

	// interruptedOverscroll stores the overscroll value from an ongoing
	// animation at the precise moment it is interrupted by a new pull()
	// gesture.
	//
	// When pull() is called while an animation (triggered by absorbImpact or
	// scrollEnd) is active, this field captures the animation's current
	// controller value (which represents the overscroll amount) immediately
	// before the animation controller is disposed.
	//
	// This captured value is then added to the overscroll amount calculated by
	// the pull() method. The primary purpose is to create a smoother visual
	// transition from an animated overscroll state to a direct, user-driven
	// pull, minimizing any abrupt visual "jumps" in the stretch effect.
	//
	// It is reset to 0.0 when an animation completes naturally via animate() or
	// when a new pull starts without a preceding active animation.
	interruptedOverscroll float64
}

const (
	// Constants from Android.
	stretchExponentialScalar = math.E / 0.33
	stretchIntensity         = 0.016

	stretchMinOverscroll = -1.0
	stretchMaxOverscroll = 1.0

	// stretchFlingVelocityFriction is a fraction used to adjust the input
	// velocity, measured in pixels, to a value between -1 and 1 when gesture
	// fling.
	stretchFlingVelocityFriction = 1.0 / 6000

	// stretchAbsorbImpactVelocityFriction is a fraction used to scale the
	// absorbed impact velocity, converting raw velocity into a normalized value
	// for simulation.
	stretchAbsorbImpactVelocityFriction = 1.0 / 3000

	// stretchMaxFlingVelocity is the maximum velocity allowed for a fling after
	// scaling to prevent applying an excessive stretch effect.
	stretchMaxFlingVelocity = 0.5

	// stretchMaxAbsorbImpactVelocity is the maximum velocity allowed when
	// absorbing an impact, ensuring the stretch effect does not exceed a
	// reasonable limit.
	stretchMaxAbsorbImpactVelocity = 1.25

	// Physical constants ported directly from Android's EdgeEffect.java:
	// https://cs.android.com/android/platform/superproject/main/+/main:frameworks/base/core/java/android/widget/EdgeEffect.java
	stretchNaturalFrequency = 24.657
	stretchDampingRatio     = 0.98

	// stretchTimeCorrectionFactor is a correction factor applied to the
	// simulation time. The physical constants stretchNaturalFrequency and
	// stretchDampingRatio were ported directly from Android's EdgeEffect.java
	// source. However, using these constants as-is resulted in an animation that
	// was noticeably faster than the native Android behavior. The underlying
	// reason for this discrepancy is unknown. This factor, determined by visual
	// comparison ("eyeballing") to match the platform's timing, is applied to
	// the elapsed time t to slow down the simulation.
	stretchTimeCorrectionFactor = 0.8

	// stretchStiffness is the stiffness coefficient for the spring, derived from
	// the natural frequency: kNaturalFrequency^2.
	stretchStiffness = stretchNaturalFrequency * stretchNaturalFrequency
)

// stretchSpringDescription is the spring description representing the stretch
// behavior of the edge effect. The spring has a mass of 1, a stiffness adjusted
// by the time correction factor squared to match platform timing, and a damping
// ratio corresponding to Android's native EdgeEffect.
//
// Flutter: widgets/overscroll_indicator.dart _StretchController._kStretchSpringDescription
var stretchSpringDescription = physics.NewSpringDescriptionWithDampingRatio(1,
	stretchStiffness*stretchTimeCorrectionFactor*stretchTimeCorrectionFactor,
	physics.SpringDescriptionWithDampingRatioOpts{Ratio: foundation.Some(stretchDampingRatio)})

func newStretchController(vsync scheduler.TickerProvider, post func(func())) *stretchController {
	return &stretchController{vsync: vsync, post: post, overscrollNotifier: foundation.NewValueNotifier(0.0)}
}

func (c *stretchController) overscroll() float64 { return c.overscrollNotifier.Value() }

func (c *stretchController) setOverscroll(newValue float64) {
	c.overscrollNotifier.SetValue(ui.ClampDouble(newValue, stretchMinOverscroll, stretchMaxOverscroll))
}

// AddListener adds the listener to the notifier of the overscroll.
func (c *stretchController) AddListener(listener foundation.VoidCallback) foundation.ListenerHandle {
	return c.overscrollNotifier.AddListener(listener)
}

// RemoveListener removes the listener from the notifier of the overscroll.
func (c *stretchController) RemoveListener(handle foundation.ListenerHandle) {
	c.overscrollNotifier.RemoveListener(handle)
}

// createStretchSimulation creates a stretching-only Simulation ported from
// Android 12.
func (c *stretchController) createStretchSimulation(velocity float64) *physics.SpringSimulation {
	return physics.NewSpringSimulation(stretchSpringDescription, c.overscroll(), 0.0, velocity*stretchTimeCorrectionFactor)
}

// absorbImpact handles a fling to the edge of the viewport at a particular
// velocity. The velocity must be positive.
func (c *stretchController) absorbImpact(velocity float64) {
	if velocity == 0.0 {
		return
	}
	scaledVelocity := ui.ClampDouble(velocity*stretchAbsorbImpactVelocityFriction, -stretchMaxAbsorbImpactVelocity, stretchMaxAbsorbImpactVelocity)
	c.animate(c.createStretchSimulation(scaledVelocity))
}

// scrollEnd is called when the overscroll ends to trigger a fling animation if
// needed.
func (c *stretchController) scrollEnd(velocity float64) {
	if velocity == 0.0 && c.overscroll() == 0.0 {
		return
	}
	scaledVelocity := ui.ClampDouble(-(velocity * stretchFlingVelocityFriction), -stretchMaxFlingVelocity, stretchMaxFlingVelocity)
	if c.controller == nil {
		c.animate(c.createStretchSimulation(scaledVelocity))
	}
}

// animate starts a new animation using the given simulation.
//
// It disposes any existing animation controller before starting a new one. It
// updates the overscroll value on each animation frame. It disposes the
// controller when the animation completes.
func (c *stretchController) animate(simulation physics.Simulation) {
	controller := animation.NewAnimationControllerUnbounded(c.vsync)
	controller.AddListener(func() {
		newOverscroll := 0.0
		if c.controller != nil {
			newOverscroll = c.controller.Value()
		}
		c.setOverscroll(newOverscroll)
	})
	controller.AnimateWith(simulation).Then(func() {
		// Deviation: Dart runs whenComplete in a microtask; the future of
		// Go completes at once, inside the tick of the controller, so the work
		// is posted, which runs it after the tick.
		c.post(func() {
			if c.controller != controller {
				return // the controller was replaced or disposed meanwhile
			}
			c.setOverscroll(0.0)
			c.interruptedOverscroll = 0.0
			c.controller.Dispose()
			c.controller = nil
		})
	})

	if c.controller != nil {
		c.controller.Dispose()
	}
	c.controller = controller
}

// pull handles a user-driven overscroll. The normalizedOverscroll argument is
// the scroll distance in logical pixels, divided by the extent of the viewport
// in the main axis.
func (c *stretchController) pull(normalizedOverscroll float64) {
	if c.controller != nil {
		c.interruptedOverscroll = c.controller.Value()
		c.controller.Dispose()
		c.controller = nil
	}

	pullDistance := normalizedOverscroll
	absDistance := math.Abs(pullDistance)
	linearIntensity := stretchIntensity * absDistance
	exponentialIntensity := stretchIntensity * (1 - math.Exp(-absDistance*stretchExponentialScalar))

	// Maintain sign of overscroll for direction.
	var directionSign float64
	switch {
	case pullDistance > 0:
		directionSign = 1
	case pullDistance < 0:
		directionSign = -1
	}
	newOverscroll := directionSign * (linearIntensity + exponentialIntensity)
	c.setOverscroll(newOverscroll + c.interruptedOverscroll)
}

func (c *stretchController) dispose() {
	if c.controller != nil {
		c.controller.Dispose()
		c.controller = nil
	}
	c.overscrollNotifier.Dispose()
}

func (c *stretchController) String() string { return "_StretchController()" }

// OverscrollIndicatorNotification is a notification that either a
// GlowingOverscrollIndicator or a StretchingOverscrollIndicator will start
// showing an overscroll indication.
//
// To prevent the indicator from showing the indication, call DisallowIndicator
// on the notification.
//
// Flutter: widgets/overscroll_indicator.dart OverscrollIndicatorNotification
type OverscrollIndicatorNotification struct {
	ViewportNotificationMixin
	// Leading is whether the indication will be shown on the leading edge of
	// the scroll view.
	//
	// Flutter: widgets/overscroll_indicator.dart OverscrollIndicatorNotification.leading
	Leading bool
	// PaintOffset controls at which offset a GlowingOverscrollIndicator draws.
	//
	// A positive offset will move the glow away from its edge, i.e. for a
	// vertical, leading indicator, a PaintOffset of 100.0 will draw the
	// indicator 100.0 pixels from the top of the edge. For a vertical indicator
	// with Leading set to false, a PaintOffset of 100.0 will draw the indicator
	// 100.0 pixels from the bottom instead.
	//
	// A negative PaintOffset is generally not useful, since the glow will be
	// clipped.
	//
	// This has no effect on a StretchingOverscrollIndicator.
	//
	// Flutter: widgets/overscroll_indicator.dart OverscrollIndicatorNotification.paintOffset
	PaintOffset float64

	accepted bool
}

// NewOverscrollIndicatorNotification creates a notification that a
// GlowingOverscrollIndicator or a StretchingOverscrollIndicator will start
// showing an overscroll indication, on the leading edge or the trailing edge.
//
// Flutter: widgets/overscroll_indicator.dart OverscrollIndicatorNotification.new
func NewOverscrollIndicatorNotification(leading bool) *OverscrollIndicatorNotification {
	return &OverscrollIndicatorNotification{Leading: leading, accepted: true}
}

// Accepted is whether the current overscroll event will allow for the indicator
// to be shown. Calling DisallowIndicator makes it false, preventing the
// overscroll indicator from showing. It is true by default.
//
// Flutter: widgets/overscroll_indicator.dart OverscrollIndicatorNotification.accepted
func (n *OverscrollIndicatorNotification) Accepted() bool { return n.accepted }

// DisallowIndicator should be called if the overscroll indicator should be
// prevented.
//
// Flutter: widgets/overscroll_indicator.dart OverscrollIndicatorNotification.disallowIndicator
func (n *OverscrollIndicatorNotification) DisallowIndicator() { n.accepted = false }

// String describes the notification.
//
// Flutter: widgets/overscroll_indicator.dart OverscrollIndicatorNotification.debugFillDescription
func (n *OverscrollIndicatorNotification) String() string {
	side := "trailing edge"
	if n.Leading {
		side = "leading edge"
	}
	return "OverscrollIndicatorNotification(" + n.describeDepth() + ", side: " + side + ")"
}

