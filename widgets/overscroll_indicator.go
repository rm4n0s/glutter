// paints on top of it. It may be nil.
//
// Flutter: widgets/overscroll_indicator.dart GlowingOverscrollIndicator.child
func (w *GlowingOverscrollIndicator) Child() Widget { return w.child }

// CreateState creates the state.
//
// Flutter: widgets/overscroll_indicator.dart GlowingOverscrollIndicator.createState
func (w *GlowingOverscrollIndicator) CreateState() State { return &glowingOverscrollIndicatorState{} }

// glowingOverscrollIndicatorState is the state of a GlowingOverscrollIndicator.
//
// Flutter: widgets/overscroll_indicator.dart _GlowingOverscrollIndicatorState
type glowingOverscrollIndicatorState struct {
	StateOf[*GlowingOverscrollIndicator]
	TickerProvider

	leadingController          *glowController
	trailingController         *glowController
	leadingAndTrailingListener foundation.Listenable
	accepted                   map[bool]bool
}

func (s *glowingOverscrollIndicatorState) InitState() {
	w := s.Widget()
	s.accepted = map[bool]bool{false: true, true: true}
	timer := WidgetsBindingOf(s.Context()).Gestures().NewTimer
	s.leadingController = newGlowController(s, timer, w.color, w.Axis())
	s.trailingController = newGlowController(s, timer, w.color, w.Axis())
	s.leadingAndTrailingListener = foundation.MergeListenables(s.leadingController, s.trailingController)
}

func (s *glowingOverscrollIndicatorState) DidUpdateWidget(oldWidget *GlowingOverscrollIndicator) {
	w := s.Widget()
	if oldWidget.color != w.color || oldWidget.Axis() != w.Axis() {
		s.leadingController.setColor(w.color)
		s.leadingController.setAxis(w.Axis())
		s.trailingController.setColor(w.color)
		s.trailingController.setAxis(w.Axis())
	}
}

func (s *glowingOverscrollIndicatorState) handleScrollNotification(notification ScrollNotification) bool {
	w := s.Widget()
	if !w.o.NotificationPredicate(notification) {
		return false
	}
	metrics := notification.Metrics()
	if metrics.Axis() != w.Axis() {
		// This widget is explicitly configured to one axis. If a notification
		// from a different axis bubbles up, do nothing.
		return false
	}

	// Update the paint offset with the current scroll position. This makes
	// sure that the glow effect correctly scrolls in line with the current
	// scroll, e.g. when scrolling in the opposite direction again to hide the
	// glow. Otherwise, the glow would always stay in a fixed position, even if
	// the top of the content already scrolled away. For example (CustomScrollView
	// with sliver before center), the scroll extent is [-200.0, 300.0], scroll
	// in the opposite direction with 10.0 pixels before glow disappears, so the
	// current pixels is -190.0, in this case, we should move the glow up 10.0
	// pixels and should not overflow the scrollable widget's edge.
	// https://github.com/flutter/flutter/issues/64149.
	s.leadingController.paintOffsetScrollPixels = -math.Min(metrics.Pixels()-metrics.MinScrollExtent(), s.leadingController.paintOffset)
	s.trailingController.paintOffsetScrollPixels = -math.Min(metrics.MaxScrollExtent()-metrics.Pixels(), s.trailingController.paintOffset)

	switch n := notification.(type) {
	case *OverscrollNotification:
		var controller *glowController
		if n.Overscroll < 0.0 {
			controller = s.leadingController
		} else if n.Overscroll > 0.0 {
			controller = s.trailingController
		}
		// An OverscrollNotification has an overscroll that is not zero, so
		// there is always a controller (Flutter: assert(controller != null)).
		isLeading := controller == s.leadingController
		// Flutter: _lastNotificationType is a Type, which is never an
		// OverscrollNotification, so the check `_lastNotificationType is!
		// OverscrollNotification` is always true at the pinned commit and the
		// confirmation is dispatched for every overscroll notification.
		confirmationNotification := NewOverscrollIndicatorNotification(isLeading)
		DispatchNotification(s.Context(), confirmationNotification)
		s.accepted[isLeading] = confirmationNotification.accepted
		if s.accepted[isLeading] {
			controller.paintOffset = confirmationNotification.PaintOffset
		}
		if s.accepted[isLeading] {
			if n.Velocity != 0.0 {
				if foundation.DebugMode && n.DragDetails.IsSome() {
					panic(errors.New(tagGlowingOverscrollVelocityWithDrag, "an OverscrollNotification with a velocity must not have drag details",
						"velocity", n.Velocity))
				}
				controller.absorbImpact(math.Abs(n.Velocity))
			} else if details, ok := n.DragDetails.Get(); ok {
				renderer := n.Context().FindRenderObject().(rendering.Box)
				size := renderer.Size()
				position := renderer.GlobalToLocal(details.GlobalPosition, nil)
				switch metrics.Axis() {
				case painting.AxisHorizontal:
					controller.pull(math.Abs(n.Overscroll), size.Width, ui.ClampDouble(position.Dy, 0.0, size.Height), size.Height)
				case painting.AxisVertical:
					controller.pull(math.Abs(n.Overscroll), size.Height, ui.ClampDouble(position.Dx, 0.0, size.Width), size.Width)
				}
			}
		}
	case *ScrollEndNotification:
		if n.DragDetails.IsSome() {
			s.leadingController.scrollEnd()
			s.trailingController.scrollEnd()
		}
	case *ScrollUpdateNotification:
		if n.DragDetails.IsSome() {
			s.leadingController.scrollEnd()
			s.trailingController.scrollEnd()
		}
	}
	return false
}

func (s *glowingOverscrollIndicatorState) Dispose() {
	s.leadingController.dispose()
	s.trailingController.dispose()
}

func (s *glowingOverscrollIndicatorState) Build(BuildContext) Widget {
	w := s.Widget()
	var leading, trailing *glowController
	if w.ShowLeading() {
		leading = s.leadingController
	}
	if w.ShowTrailing() {
		trailing = s.trailingController
	}
	return NewNotificationListener(s.handleScrollNotification,
		NewRepaintBoundary(
			NewCustomPaint(NewRepaintBoundary(w.child), CustomPaintOpts{
				ForegroundPainter: newGlowingOverscrollIndicatorPainter(leading, trailing, w.axisDirection, s.leadingAndTrailingListener),
			})))
}

// glowState is the phase of a glow.
//
// Flutter: widgets/overscroll_indicator.dart _GlowState
type glowState int

const (
	glowStateIdle glowState = iota
	glowStateAbsorb
	glowStatePull
	glowStateRecede
)

const (
	glowRecedeTime    = 600 * time.Millisecond
	glowPullTime      = 167 * time.Millisecond
	glowPullHoldTime  = 167 * time.Millisecond
	glowPullDecayTime = 2000 * time.Millisecond
	// glowCrossAxisHalfTime is (Duration.microsecondsPerSecond / 60.0).round().
	glowCrossAxisHalfTime = 16667 * time.Microsecond

	glowMaxOpacity            = 0.5
	glowPullOpacityGlowFactor = 0.8
	glowVelocityGlowFactor    = 0.00006
	glowSqrt3                 = 1.73205080757 // const math.sqrt(3)
	glowWidthToHeightFactor   = (3.0 / 4.0) * (2.0 - glowSqrt3)

	// absorbed velocities are clamped to the range glowMinVelocity..glowMaxVelocity
	glowMinVelocity = 100.0   // logical pixels per second
	glowMaxVelocity = 10000.0 // logical pixels per second
)

// glowController animates the glow of one side of a scrollable. The Glow logic
// is a port of the logic in
// https://android.googlesource.com/platform/frameworks/base/+/main/core/java/android/widget/EdgeEffect.java
// as of December 2016.
//
// Flutter: widgets/overscroll_indicator.dart _GlowController
type glowController struct {
	foundation.ChangeNotifier
	newTimer func(d time.Duration, fn func()) *gestures.Timer

	// animation of the main axis direction
	state                   glowState
	glowController          *animation.AnimationController
	pullRecedeTimer         *gestures.Timer
	paintOffset             float64
	paintOffsetScrollPixels float64

	// animation values
	decelerator      *animation.CurvedAnimation
	glowOpacityTween *animation.Tween[float64]
	glowOpacity      animation.Animation[float64]
	glowSizeTween    *animation.Tween[float64]
	glowSize         animation.Animation[float64]

	// animation of the cross axis position
	displacementTicker     *scheduler.Ticker
	displacementTickerLast foundation.Opt[time.Duration]
	displacementTarget     float64
	displacement           float64

	// tracking the pull distance
	pullDistance float64

	color ui.Color
	axis  painting.Axis
}

func newGlowController(vsync scheduler.TickerProvider, newTimer func(d time.Duration, fn func()) *gestures.Timer, color ui.Color, axis painting.Axis) *glowController {
	c := &glowController{newTimer: newTimer, color: color, axis: axis, displacementTarget: 0.5, displacement: 0.5}
	c.glowController = animation.NewAnimationController(vsync)
	c.glowController.AddStatusListener(c.changePhase)
	c.decelerator = animation.NewCurvedAnimation(c.glowController, animation.Curves.Decelerate)
	c.decelerator.AddListener(c.NotifyListeners)
	c.glowOpacityTween = animation.NewTween(0.0, 0.0)
	c.glowOpacity = animation.Drive[float64](c.decelerator, c.glowOpacityTween)
	c.glowSizeTween = animation.NewTween(0.0, 0.0)
	c.glowSize = animation.Drive[float64](c.decelerator, c.glowSizeTween)
	c.displacementTicker = vsync.CreateTicker(c.tickDisplacement)
	return c
}

func (c *glowController) setColor(value ui.Color) {
	if c.color == value {
		return
	}
	c.color = value
	c.NotifyListeners()
}

func (c *glowController) setAxis(value painting.Axis) {
	if c.axis == value {
		return
	}
	c.axis = value
	c.NotifyListeners()
}

func (c *glowController) dispose() {
	c.glowController.Dispose()
	c.decelerator.Dispose()
	c.displacementTicker.Dispose()
	if c.pullRecedeTimer != nil {
		c.pullRecedeTimer.Cancel()
	}
	c.Dispose()
}

func (c *glowController) cancelPullRecedeTimer() {
	if c.pullRecedeTimer != nil {
		c.pullRecedeTimer.Cancel()
	}
}

// absorbImpact handles a scroll slamming into the edge at a particular
// velocity. The velocity must be positive.
func (c *glowController) absorbImpact(velocity float64) {
	c.cancelPullRecedeTimer()
	c.pullRecedeTimer = nil
	velocity = ui.ClampDouble(velocity, glowMinVelocity, glowMaxVelocity)
	if c.state == glowStateIdle {
		c.glowOpacityTween.Begin = 0.3
	} else {
		c.glowOpacityTween.Begin = c.glowOpacity.Value()
	}
	c.glowOpacityTween.End = ui.ClampDouble(velocity*glowVelocityGlowFactor, c.glowOpacityTween.Begin, glowMaxOpacity)
	c.glowSizeTween.Begin = c.glowSize.Value()
	c.glowSizeTween.End = math.Min(0.025+7.5e-7*velocity*velocity, 1.0)
	c.glowController.Duration = foundation.Some(time.Duration(math.Round(0.15+velocity*0.02)) * time.Millisecond)
	c.glowController.Forward(0.0)
	c.displacement = 0.5
	c.state = glowStateAbsorb
}

// pull handles a user-driven overscroll.
//
// The overscroll argument is the scroll distance in logical pixels, the extent
// argument is the total dimension of the viewport in the main axis in logical
// pixels, the crossAxisOffset argument is the distance from the leading (left
// or top) edge of the cross axis of the viewport, and the crossExtent is the
// size of the cross axis. For example, a pull of 50 pixels up the middle of a
// 200 pixel high and 100 pixel wide vertical viewport is a call of
// pull(50.0, 200.0, 50.0, 100.0). The overscroll value is positive regardless
// of the direction.
func (c *glowController) pull(overscroll, extent, crossAxisOffset, crossExtent float64) {
	c.cancelPullRecedeTimer()
	c.pullDistance += overscroll / 200.0 // This factor is magic. Not clear why we need it to match Android.
	c.glowOpacityTween.Begin = c.glowOpacity.Value()
	c.glowOpacityTween.End = math.Min(c.glowOpacity.Value()+overscroll/extent*glowPullOpacityGlowFactor, glowMaxOpacity)
	height := math.Min(extent, crossExtent*glowWidthToHeightFactor)
	c.glowSizeTween.Begin = c.glowSize.Value()
	c.glowSizeTween.End = math.Max(1.0-1.0/(0.7*math.Sqrt(c.pullDistance*height)), c.glowSize.Value())
	c.displacementTarget = crossAxisOffset / crossExtent
	if c.displacementTarget != c.displacement {
		if !c.displacementTicker.IsTicking() {
			c.displacementTicker.Start()
		}
	} else {
		c.displacementTicker.Stop()
		c.displacementTickerLast = foundation.None[time.Duration]()
	}
	c.glowController.Duration = foundation.Some(glowPullTime)
	if c.state != glowStatePull {
		c.glowController.Forward(0.0)
		c.state = glowStatePull
	} else if !c.glowController.IsAnimating() {
		c.NotifyListeners()
	}
	c.pullRecedeTimer = c.newTimer(glowPullHoldTime, func() { c.recede(glowPullDecayTime) })
}

func (c *glowController) scrollEnd() {
	if c.state == glowStatePull {
		c.recede(glowRecedeTime)
	}
}

func (c *glowController) changePhase(status animation.AnimationStatus) {
	if !status.IsCompleted() {
		return
	}
	switch c.state {
	case glowStateAbsorb:
		c.recede(glowRecedeTime)
	case glowStateRecede:
		c.state = glowStateIdle
		c.pullDistance = 0.0
	case glowStatePull, glowStateIdle:
	}
}

func (c *glowController) recede(duration time.Duration) {
	if c.state == glowStateRecede || c.state == glowStateIdle {
		return
	}
	c.cancelPullRecedeTimer()
	c.pullRecedeTimer = nil
	c.glowOpacityTween.Begin = c.glowOpacity.Value()
	c.glowOpacityTween.End = 0.0
	c.glowSizeTween.Begin = c.glowSize.Value()
	c.glowSizeTween.End = 0.0
	c.glowController.Duration = foundation.Some(duration)
	c.glowController.Forward(0.0)
	c.state = glowStateRecede
}

func (c *glowController) tickDisplacement(elapsed time.Duration) {
	if last, ok := c.displacementTickerLast.Get(); ok {
		t := float64((elapsed - last).Microseconds())
		c.displacement = c.displacementTarget - (c.displacementTarget-c.displacement)*math.Pow(2.0, -t/float64(glowCrossAxisHalfTime.Microseconds()))
		c.NotifyListeners()
	}
	if physics.NearEqual(c.displacementTarget, c.displacement, physics.NewTolerance().Distance) {
		c.displacementTicker.Stop()
		c.displacementTickerLast = foundation.None[time.Duration]()
	} else {
		c.displacementTickerLast = foundation.Some(elapsed)
	}
}

func (c *glowController) paint(canvas *ui.Canvas, size ui.Size) {
	if c.glowOpacity.Value() == 0.0 {
		return
	}
	baseGlowScale := 1.0
	if size.Width > size.Height {
		baseGlowScale = size.Height / size.Width
	}
	radius := size.Width * 3.0 / 2.0
	height := math.Min(size.Height, size.Width*glowWidthToHeightFactor)
	scaleY := c.glowSize.Value() * baseGlowScale
	rect := ui.NewRectFromLTWH(0.0, 0.0, size.Width, height)
	center := ui.Offset{Dx: (size.Width / 2.0) * (0.5 + c.displacement), Dy: height - radius}
	paint := ui.NewPaint()
	paint.SetColor(c.color.WithOpacity(c.glowOpacity.Value()))
	canvas.Save()
	canvas.Translate(0.0, c.paintOffset+c.paintOffsetScrollPixels)
	canvas.Scale(1.0, scaleY)
	canvas.ClipRect(rect)
	canvas.DrawCircle(center, radius, paint)
	canvas.Restore()
}

func (c *glowController) String() string {
	return fmt.Sprintf("_GlowController(color: %v, axis: %s)", c.color, axisName(c.axis))
}

// axisName is Dart's Axis.name.
func axisName(a painting.Axis) string {
	if a == painting.AxisHorizontal {
		return "horizontal"
	}
	return "vertical"
}

// glowingOverscrollIndicatorPainter paints the glows of the two sides.
//
// Flutter: widgets/overscroll_indicator.dart _GlowingOverscrollIndicatorPainter
type glowingOverscrollIndicatorPainter struct {
	rendering.CustomPainterBase
	// leadingController is the controller for the overscroll glow on the side
	// with negative scroll offsets; for a vertical downwards viewport, the top
	// side.
	leadingController *glowController
	// trailingController is the controller for the overscroll glow on the side
	// with positive scroll offsets; for a vertical downwards viewport, the
	// bottom side.
	trailingController *glowController
	// axisDirection is the direction of the viewport.
	axisDirection painting.AxisDirection
}

func newGlowingOverscrollIndicatorPainter(leading, trailing *glowController, axisDirection painting.AxisDirection, repaint foundation.Listenable) *glowingOverscrollIndicatorPainter {
	return &glowingOverscrollIndicatorPainter{CustomPainterBase: rendering.NewCustomPainterBase(repaint),
		leadingController: leading, trailingController: trailing, axisDirection: axisDirection}
}

const glowPiOver2 = math.Pi / 2.0

func (p *glowingOverscrollIndicatorPainter) paintSide(canvas *ui.Canvas, size ui.Size, controller *glowController, axisDirection painting.AxisDirection, growthDirection rendering.GrowthDirection) {
	if controller == nil {
		return
	}
	switch rendering.ApplyGrowthDirectionToAxisDirection(axisDirection, growthDirection) {
	case painting.AxisDirectionUp:
		controller.paint(canvas, size)
	case painting.AxisDirectionDown:
		canvas.Save()
		canvas.Translate(0.0, size.Height)
		canvas.Scale(1.0, -1.0)
		controller.paint(canvas, size)
		canvas.Restore()
	case painting.AxisDirectionLeft:
		canvas.Save()
		canvas.Rotate(glowPiOver2)
		canvas.Scale(1.0, -1.0)
		controller.paint(canvas, ui.Size{Width: size.Height, Height: size.Width})
		canvas.Restore()
	case painting.AxisDirectionRight:
		canvas.Save()
		canvas.Translate(size.Width, 0.0)
		canvas.Rotate(glowPiOver2)
		controller.paint(canvas, ui.Size{Width: size.Height, Height: size.Width})
		canvas.Restore()
	}
}

// Paint paints the glow of the leading side, then the one of the trailing side.
//
// Flutter: widgets/overscroll_indicator.dart _GlowingOverscrollIndicatorPainter.paint
func (p *glowingOverscrollIndicatorPainter) Paint(canvas *ui.Canvas, size ui.Size) {
	p.paintSide(canvas, size, p.leadingController, p.axisDirection, rendering.GrowthDirectionReverse)
	p.paintSide(canvas, size, p.trailingController, p.axisDirection, rendering.GrowthDirectionForward)
}

// ShouldRepaint is whether the controllers differ from the old painter's.
//
// Flutter: widgets/overscroll_indicator.dart _GlowingOverscrollIndicatorPainter.shouldRepaint
func (p *glowingOverscrollIndicatorPainter) ShouldRepaint(oldDelegate rendering.CustomPainter) bool {
	old, ok := oldDelegate.(*glowingOverscrollIndicatorPainter)
	if !ok {
		return true
	}
	return old.leadingController != p.leadingController || old.trailingController != p.trailingController
}

func (p *glowingOverscrollIndicatorPainter) String() string {
	return fmt.Sprintf("_GlowingOverscrollIndicatorPainter(%v, %v)", p.leadingController, p.trailingController)
}

// StretchingOverscrollIndicatorOpts are the optional parameters of
// NewStretchingOverscrollIndicator.
//
// Flutter: widgets/overscroll_indicator.dart StretchingOverscrollIndicator.new
type StretchingOverscrollIndicatorOpts struct {
	// Key is the key of the widget.
	Key foundation.Key
	// NotificationPredicate is a check that specifies whether a
	// ScrollNotification should be handled by this widget; the default is
	// DefaultScrollNotificationPredicate (the depth is 0).
	NotificationPredicate ScrollNotificationPredicate
	// ClipBehavior is whether the stretched content is clipped, and how; the
	// default is ClipHardEdge.
	ClipBehavior ui.Clip
}

// StretchingOverscrollIndicator is a Material Design visual indication that a
// scroll view has overscrolled.
//
// It listens for ScrollNotifications in order to stretch the content of the
// Scrollable. These notifications are typically generated by a ScrollView, such
// as a ListView or a GridView.
//
// When triggered, it dispatches an OverscrollIndicatorNotification before
// showing an overscroll indication. To prevent the indicator from showing the
// indication, call OverscrollIndicatorNotification.DisallowIndicator on the
// notification.
//
// MaterialScrollBehavior.BuildOverscrollIndicator creates it on the platforms
// (Android) that commonly use this type of overscroll indication when
// ThemeData.UseMaterial3 is true. Otherwise, when UseMaterial3 is false, a
// GlowingOverscrollIndicator is used instead.
//
// Flutter: widgets/overscroll_indicator.dart StretchingOverscrollIndicator
type StretchingOverscrollIndicator struct {
	StatefulWidget
	axisDirection painting.AxisDirection
	child         Widget
	o             StretchingOverscrollIndicatorOpts
}

// NewStretchingOverscrollIndicator creates a visual indication that a scroll
// view has overscrolled by applying a stretch transformation to the content. In
// order for the widget to display an overscroll indication, the child must
// contain a widget that generates a ScrollNotification, such as a ListView or a
// GridView. The child may be nil.
//
// Flutter: widgets/overscroll_indicator.dart StretchingOverscrollIndicator.new
func NewStretchingOverscrollIndicator(axisDirection painting.AxisDirection, child Widget, opts ...StretchingOverscrollIndicatorOpts) *StretchingOverscrollIndicator {
	o := firstOpts(opts)
	if o.NotificationPredicate == nil {
		o.NotificationPredicate = DefaultScrollNotificationPredicate
	}
	if o.ClipBehavior == ui.ClipUnspecified {
		o.ClipBehavior = ui.ClipHardEdge
	}
	return &StretchingOverscrollIndicator{StatefulWidget: NewStatefulWidgetBase(WidgetOpts{Key: o.Key}),
		axisDirection: axisDirection, child: child, o: o}
}

