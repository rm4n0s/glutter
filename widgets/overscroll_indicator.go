// GlowingOverscrollIndicatorOpts are the optional parameters of
// NewGlowingOverscrollIndicator.
//
// Flutter: widgets/overscroll_indicator.dart GlowingOverscrollIndicator.new
type GlowingOverscrollIndicatorOpts struct {
	// Key is the key of the widget.
	Key foundation.Key
	// ShowLeading is whether to show the overscroll glow on the side with
	// negative scroll offsets (for a vertical downwards viewport, the top
	// side); the default is true.
	ShowLeading foundation.Opt[bool]
	// ShowTrailing is whether to show the overscroll glow on the side with
	// positive scroll offsets (for a vertical downwards viewport, the bottom
	// side); the default is true.
	ShowTrailing foundation.Opt[bool]
	// NotificationPredicate is a check that specifies whether a
	// ScrollNotification should be handled by this widget; the default is
	// DefaultScrollNotificationPredicate (the depth is 0).
	NotificationPredicate ScrollNotificationPredicate
}

// GlowingOverscrollIndicator is a visual indication that a scroll view has
// overscrolled.
//
// It listens for ScrollNotifications in order to control the overscroll
// indication. These notifications are typically generated by a ScrollView, such
// as a ListView or a GridView.
//
// It dispatches an OverscrollIndicatorNotification before showing an overscroll
// indication. To prevent the indicator from showing the indication, call
// OverscrollIndicatorNotification.DisallowIndicator on the notification.
//
// ScrollBehavior.BuildOverscrollIndicator creates it on the platforms (Android
// and Fuchsia) that commonly use this type of overscroll indication. In a
// MaterialApp, the edge glow color is the ColorScheme.secondary color of the
// theme.
//
// When it is built for a CustomScrollView, the indicator applies to the entire
// scrollable area, whatever the slivers are. To move the glow, listen for the
// OverscrollIndicatorNotification and set its PaintOffset, or use a
// NestedScrollView.
//
// Flutter: widgets/overscroll_indicator.dart GlowingOverscrollIndicator
type GlowingOverscrollIndicator struct {
	StatefulWidget
	axisDirection painting.AxisDirection
	color         ui.Color
	child         Widget
	o             GlowingOverscrollIndicatorOpts
}

// NewGlowingOverscrollIndicator creates a visual indication that a scroll view
// has overscrolled. In order for the widget to display an overscroll
// indication, the child must contain a widget that generates a
// ScrollNotification, such as a ListView or a GridView. The child may be nil.
//
// Flutter: widgets/overscroll_indicator.dart GlowingOverscrollIndicator.new
func NewGlowingOverscrollIndicator(axisDirection painting.AxisDirection, color ui.Color, child Widget, opts ...GlowingOverscrollIndicatorOpts) *GlowingOverscrollIndicator {
	o := firstOpts(opts)
	if o.NotificationPredicate == nil {
		o.NotificationPredicate = DefaultScrollNotificationPredicate
	}
	return &GlowingOverscrollIndicator{StatefulWidget: NewStatefulWidgetBase(WidgetOpts{Key: o.Key}),
		axisDirection: axisDirection, color: color, child: child, o: o}
}

// ShowLeading is whether to show the overscroll glow on the side with negative
// scroll offsets. For a vertical downwards viewport, this is the top side.
//
// Flutter: widgets/overscroll_indicator.dart GlowingOverscrollIndicator.showLeading
func (w *GlowingOverscrollIndicator) ShowLeading() bool { return w.o.ShowLeading.OrElse(true) }

// ShowTrailing is whether to show the overscroll glow on the side with positive
// scroll offsets. For a vertical downwards viewport, this is the bottom side.
//
// Flutter: widgets/overscroll_indicator.dart GlowingOverscrollIndicator.showTrailing
func (w *GlowingOverscrollIndicator) ShowTrailing() bool { return w.o.ShowTrailing.OrElse(true) }

// AxisDirection is the direction of positive scroll offsets in the Scrollable
// whose overscrolls are to be visualized.
//
// Flutter: widgets/overscroll_indicator.dart GlowingOverscrollIndicator.axisDirection
func (w *GlowingOverscrollIndicator) AxisDirection() painting.AxisDirection { return w.axisDirection }

// Axis is the axis along which scrolling occurs in the Scrollable whose
// overscrolls are to be visualized.
//
// Flutter: widgets/overscroll_indicator.dart GlowingOverscrollIndicator.axis
func (w *GlowingOverscrollIndicator) Axis() painting.Axis {
	return painting.AxisDirectionToAxis(w.axisDirection)
}

// Color is the color of the glow. The alpha channel is ignored.
//
// Flutter: widgets/overscroll_indicator.dart GlowingOverscrollIndicator.color
func (w *GlowingOverscrollIndicator) Color() ui.Color { return w.color }

