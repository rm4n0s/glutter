// ScrollNotification should be handled by this widget.
//
// Flutter: widgets/overscroll_indicator.dart GlowingOverscrollIndicator.notificationPredicate
func (w *GlowingOverscrollIndicator) NotificationPredicate() ScrollNotificationPredicate {
	return w.o.NotificationPredicate
}

